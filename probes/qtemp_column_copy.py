"""Renaming a column by copying it, in QTEMP (#258 F).

Db2 for i has no statement to rename a column. The opt-in rename adds a column with the
new name, copies the values and drops the old column. This probe tries the steps on
tables with rows, in QTEMP:

1. ``ADD COLUMN ... BEFORE <old>``: does the new column take the old one's place
   (the order ``SELECT *`` returns), also with ``FOR COLUMN <system name>``?
2. ``UPDATE ... SET new = old``, then ``NOT NULL`` and the default on the new column in
   one ``ALTER TABLE``, then ``DROP COLUMN old RESTRICT``: values and order afterwards.
   2b: forms of several changes to one column in one ``ALTER TABLE``.
3. An identity column: ``DROP IDENTITY`` on the old one, a new ``GENERATED BY DEFAULT
   AS IDENTITY`` column ``BEFORE`` it, the values copied, ``RESTART WITH``, an insert.
4. ``DROP COLUMN ... RESTRICT`` with a dependent index, view and trigger on the old
   column, an index on another column as the control, and without a keyword.
5. Read only: the columns of the catalog views the checks would read (``SYSCOLUMNS``,
   ``SYSTRIGCOL``, ``SYSCOLAUTH``, ``SYSCONTROLS``, ``SYSVIEWDEP``, ``SYSINDEXES``).

QTEMP only: tables, an index, a view and a trigger, all gone with the job. CPA32B2 is
suppressed for the probe's own job as the schema editor does in a migration (a QTEMP
copy of QAQQINI, discarded at the end). Like probe 24 it runs only when the job's
inquiry message reply is *RQD, so a statement that still sends CPA32B2 is cancelled
(HY008) and the job never waits. Rows are written WITH NC (QTEMP has no journal).
One connection, no retries.

Usage (inside the "tests" container):
    nox -s probe -- column_copy

Findings go to docs/IBMI_NOTES.md.
"""

from __future__ import annotations

from typing import Any

from _common import Settings
from qtemp_alter_table import BACKEND, _execute, _inquiry, _rows
from qtemp_later_flags import _step

NEEDS_CONNECTION = True
AUTOCOMMIT = True

TABLE = "QTEMP.PCCT"
IDENTITY = "QTEMP.PCCI"
SETUP = (
    f"CREATE TABLE {TABLE} (ID INTEGER NOT NULL, A INTEGER, "
    "OLD_NAME VARCHAR(10) NOT NULL DEFAULT 'x', Z INTEGER)",
    f"INSERT INTO {TABLE} VALUES (1, 10, 'one', 100), (2, 20, 'two', 200), "
    "(3, 30, 'three', 300) WITH NC",
)
CATALOG = ("SYSCOLUMNS", "SYSTRIGCOL", "SYSCOLAUTH", "SYSCONTROLS", "SYSVIEWDEP", "SYSINDEXES")


def connection_attributes(settings: Settings) -> dict[str, str]:
    import pyodbc

    pyodbc.pooling = False
    return BACKEND


def _columns(conn, table: str) -> list[str] | dict[str, Any]:
    """The column order SELECT * returns (QTEMP is not in the catalog)."""
    import pyodbc

    cursor = conn.cursor()
    try:
        cursor.execute(f"SELECT * FROM {table} FETCH FIRST 1 ROW ONLY")
        return [column[0] for column in cursor.description]
    except pyodbc.Error as exc:
        return {"result": "error", "message": str(exc.args[-1])[:160]}
    finally:
        cursor.close()


def _fresh(conn) -> None:
    for name in ("QTEMP.PCCV",):
        _execute(conn, f"DROP VIEW {name}")
    _execute(conn, f"DROP TABLE {TABLE}")
    for sql in SETUP:
        outcome = _execute(conn, sql)
        if outcome["result"] != "ok":
            raise RuntimeError(f"setup failed: {sql}: {outcome}")


def _copy_steps(conn, results: dict[str, Any]) -> None:
    _fresh(conn)
    _step(results, "1. columns before", {"columns": _columns(conn, TABLE)})
    _step(
        results,
        "1. add column BEFORE, with a system name",
        _execute(
            conn,
            f'ALTER TABLE {TABLE} ADD COLUMN "NEW_LONG_NAME" FOR COLUMN NEWNAME '
            "VARCHAR(10) BEFORE OLD_NAME",
        ),
    )
    _step(results, "1. columns after add", {"columns": _columns(conn, TABLE)})
    _step(
        results,
        "2. copy",
        _execute(conn, f'UPDATE {TABLE} SET "NEW_LONG_NAME" = OLD_NAME WITH NC'),
    )
    _step(
        results,
        "2. NOT NULL and default in one ALTER TABLE",
        _execute(
            conn,
            f'ALTER TABLE {TABLE} ALTER COLUMN "NEW_LONG_NAME" SET NOT NULL '
            "ALTER COLUMN \"NEW_LONG_NAME\" SET DEFAULT 'x'",
        ),
    )
    _step(
        results,
        "2. drop the old column RESTRICT",
        _execute(conn, f"ALTER TABLE {TABLE} DROP COLUMN OLD_NAME RESTRICT"),
    )
    _step(
        results,
        "2. columns and rows after",
        {
            "columns": _columns(conn, TABLE),
            "rows": _rows(conn, f"SELECT * FROM {TABLE} ORDER BY ID"),
            "insert with the default": _execute(
                conn, f"INSERT INTO {TABLE} (ID, A, Z) VALUES (4, 40, 400) WITH NC"
            ),
            "the default row": _rows(conn, f'SELECT "NEW_LONG_NAME" FROM {TABLE} WHERE ID = 4'),
        },
    )


SAME_COLUMN = (
    ("type and NOT NULL", 'ALTER COLUMN "A" SET DATA TYPE BIGINT SET NOT NULL'),
    ("NOT NULL and default", 'ALTER COLUMN "A" SET NOT NULL SET DEFAULT 5'),
    ("type and default", 'ALTER COLUMN "A" SET DATA TYPE BIGINT SET DEFAULT 6'),
    (
        "type, NOT NULL and default",
        'ALTER COLUMN "A" SET DATA TYPE BIGINT SET NOT NULL SET DEFAULT 7',
    ),
    ("type and DROP NOT NULL", 'ALTER COLUMN "ID" SET DATA TYPE BIGINT DROP NOT NULL'),
    ("DROP DEFAULT and DROP NOT NULL", 'ALTER COLUMN "OLD_NAME" DROP DEFAULT DROP NOT NULL'),
    ("type and DROP DEFAULT", 'ALTER COLUMN "OLD_NAME" SET DATA TYPE VARCHAR(20) DROP DEFAULT'),
    ("two columns (control)", 'ALTER COLUMN "A" SET NOT NULL ALTER COLUMN "Z" SET NOT NULL'),
)


def _same_column(conn, results: dict[str, Any]) -> None:
    """Several changes to one column in one ALTER TABLE (supports_combined_alters):
    ``ALTER COLUMN x ... ALTER COLUMN x ...`` is SQL0612; one ALTER COLUMN clause with
    several alterations?"""
    for label, clause in SAME_COLUMN:
        _fresh(conn)
        outcome = _execute(conn, f"ALTER TABLE {TABLE} {clause}")
        outcome["insert without the columns"] = _execute(
            conn, f"INSERT INTO {TABLE} (ID) VALUES (9) WITH NC"
        )
        outcome["the row"] = _rows(conn, f"SELECT * FROM {TABLE} WHERE ID = 9")
        _step(results, f"2b. same column: {label}", outcome)


def _identity_steps(conn, results: dict[str, Any]) -> None:
    _execute(conn, f"DROP TABLE {IDENTITY}")
    _execute(
        conn,
        f"CREATE TABLE {IDENTITY} (OLD_ID INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL, "
        "V INTEGER)",
    )
    _execute(conn, f"INSERT INTO {IDENTITY} (V) VALUES (10), (20), (30) WITH NC")
    _execute(conn, f"DELETE FROM {IDENTITY} WHERE V = 20 WITH NC")  # a gap: 1, 3
    for key, sql in (
        (
            "3. drop identity of the old column",
            f"ALTER TABLE {IDENTITY} ALTER COLUMN OLD_ID DROP IDENTITY",
        ),
        (
            "3. add an identity column BEFORE",
            f"ALTER TABLE {IDENTITY} ADD COLUMN NEW_ID INTEGER GENERATED BY DEFAULT AS IDENTITY "
            "NOT NULL BEFORE OLD_ID",
        ),
    ):
        _step(results, key, _execute(conn, sql))
    _step(
        results,
        "3. values the new identity column got",
        {"rows": _rows(conn, f"SELECT * FROM {IDENTITY} ORDER BY V")},
    )
    for key, sql in (
        ("3. copy", f"UPDATE {IDENTITY} SET NEW_ID = OLD_ID WITH NC"),
        ("3. restart", f"ALTER TABLE {IDENTITY} ALTER COLUMN NEW_ID RESTART WITH 4"),
        ("3. drop the old column", f"ALTER TABLE {IDENTITY} DROP COLUMN OLD_ID RESTRICT"),
        ("3. insert", f"INSERT INTO {IDENTITY} (V) VALUES (40) WITH NC"),
    ):
        _step(results, key, _execute(conn, sql))
    _step(
        results,
        "3. columns and rows after",
        {
            "columns": _columns(conn, IDENTITY),
            "rows": _rows(conn, f"SELECT * FROM {IDENTITY} ORDER BY V"),
        },
    )
    _execute(conn, f"DROP TABLE {IDENTITY}")


def _dependents(conn, results: dict[str, Any]) -> None:
    cases = (
        ("index on the column", f"CREATE INDEX QTEMP.PCCX ON {TABLE} (OLD_NAME)", "RESTRICT"),
        (
            "index on another column (control)",
            f"CREATE INDEX QTEMP.PCCX ON {TABLE} (A)",
            "RESTRICT",
        ),
        (
            "view on the column",
            f"CREATE VIEW QTEMP.PCCV AS SELECT ID, OLD_NAME FROM {TABLE}",
            "RESTRICT",
        ),
        (
            "view on other columns (control)",
            f"CREATE VIEW QTEMP.PCCV AS SELECT ID, A FROM {TABLE}",
            "RESTRICT",
        ),
        (
            "trigger reading the column",
            f"CREATE TRIGGER QTEMP.PCCTR AFTER UPDATE ON {TABLE} REFERENCING NEW AS N "
            "FOR EACH ROW MODE DB2ROW WHEN (N.OLD_NAME = 'zzz') "
            f"UPDATE {TABLE} SET A = 0 WHERE ID = -1",
            "RESTRICT",
        ),
        ("index on the column, no keyword", f"CREATE INDEX QTEMP.PCCX ON {TABLE} (OLD_NAME)", ""),
        (
            "view on the column, no keyword",
            f"CREATE VIEW QTEMP.PCCV AS SELECT ID, OLD_NAME FROM {TABLE}",
            "",
        ),
    )
    for label, create, keyword in cases:
        _fresh(conn)
        _execute(conn, "DROP TRIGGER QTEMP.PCCTR")
        made = _execute(conn, create)
        outcome = _execute(conn, f"ALTER TABLE {TABLE} DROP COLUMN OLD_NAME {keyword}".rstrip())
        outcome["create"] = made
        outcome["columns after"] = _columns(conn, TABLE)
        outcome["index left"] = _execute(conn, "SELECT COUNT(*) FROM QTEMP.PCCX")["result"]
        outcome["view left"] = _execute(conn, "SELECT COUNT(*) FROM QTEMP.PCCV")["result"]
        _step(results, f"4. drop column: {label}", outcome)
        _execute(conn, "DROP TRIGGER QTEMP.PCCTR")
        _execute(conn, "DROP VIEW QTEMP.PCCV")
        _execute(conn, "DROP INDEX QTEMP.PCCX")


def run(settings: Settings, conn) -> dict[str, Any]:
    inquiry = _inquiry()
    cursor = conn.cursor()
    try:
        reply = inquiry.read_reply(cursor)
    finally:
        cursor.close()
    results: dict[str, Any] = {
        "scope": "QTEMP only (PCC* objects, gone with the job)",
        "inquiry message reply": reply,
    }
    if reply != "*RQD":
        print(f"  the job's inquiry message reply is {reply}, not *RQD; nothing was run")
        return results
    try:
        for sql in inquiry.SUPPRESS_SQL:
            _step(results, f"suppress: {sql}", _execute(conn, sql))
        _copy_steps(conn, results)
        _same_column(conn, results)
        _identity_steps(conn, results)
        _dependents(conn, results)
    finally:
        _execute(conn, "DROP TRIGGER QTEMP.PCCTR")
        _execute(conn, "DROP VIEW QTEMP.PCCV")
        _execute(conn, f"DROP TABLE {TABLE}")
        _execute(conn, f"DROP TABLE {IDENTITY}")
        _step(results, "discard the QAQQINI copy", _execute(conn, inquiry.DISCARD_SQL))
    for view in CATALOG:
        _step(
            results,
            f"5. catalog columns of QSYS2.{view}",
            {
                "columns": [
                    row[0]
                    for row in _rows(
                        conn,
                        "SELECT COLUMN_NAME FROM QSYS2.SYSCOLUMNS WHERE TABLE_SCHEMA = 'QSYS2' "
                        "AND TABLE_NAME = ? ORDER BY ORDINAL_POSITION",
                        (view,),
                    )
                ]
            },
        )
    return results
