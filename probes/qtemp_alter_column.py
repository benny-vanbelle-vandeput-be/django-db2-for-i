"""ALTER COLUMN forms the schema editor writes, in QTEMP (phase 4, step C item 7).

Writes only to QTEMP (a table and two indexes that disappear with the
job). Like probe 24 (qtemp_alter_table) it changes no job
attribute and runs only when the job's inquiry message reply is *RQD, so a
statement that sends CPA32B2 is cancelled (HY008) and changes nothing.

Every case runs on a fresh two-row table and records the outcome, the last
job log messages and the column afterwards (as the driver describes it, with
the rows' values), plus a check per case:

- widening a column that has an index (the index is still there);
- widening a column with a unique index (it still holds). A unique
  constraint cannot be created in QTEMP under commitment control (SQL7008:
  QTEMP is not journaled), so the unique index stands in for it here;
- widening a DECIMAL in precision and scale, DECIMAL(5, 2) -> DECIMAL(7, 3);
- SET DEFAULT with a UX'...' literal through ALTER (the value an insert
  without the column gets);
- widening an identity column, INTEGER -> BIGINT, with SET DATA TYPE BIGINT
  and with the identity clause repeated (numbering after the change).

Findings go to docs/IBMI_NOTES.md.
"""

from __future__ import annotations

from typing import Any

from _common import Settings
from qtemp_alter_table import BACKEND, JOB_LOG, _execute, _inquiry, _rows, _ux

NEEDS_CONNECTION = True
AUTOCOMMIT = True

TABLE = "QTEMP.PACT"
INDEX = "QTEMP.PACI"
UNIQUE = "QTEMP.PACU"
CREATE = (
    f"CREATE TABLE {TABLE} (ID INTEGER GENERATED BY DEFAULT AS IDENTITY, IX INTEGER, "
    "UQ NVARCHAR(10), D DECIMAL(5, 2), V NVARCHAR(30))"
)
SETUP = (
    CREATE,
    f"CREATE INDEX {INDEX} ON {TABLE} (IX)",
    f"CREATE UNIQUE INDEX {UNIQUE} ON {TABLE} (UQ)",
    f"INSERT INTO {TABLE} (IX, UQ, D, V) VALUES (1, 'a', 123.45, 'one') WITH NC",
    f"INSERT INTO {TABLE} (IX, UQ, D, V) VALUES (2, 'b', -0.01, 'two') WITH NC",
)
# Text that needs the UX form in a DEFAULT (a quote, a percent sign, non-ASCII).
DEFAULT_TEXT = "O'Brien 100% Ж"

# (label, column, statement, check); the check runs after the statement.
CASES = [
    (
        "INTEGER -> BIGINT on an indexed column",
        "IX",
        f"ALTER TABLE {TABLE} ALTER COLUMN IX SET DATA TYPE BIGINT",
        "index",
    ),
    (
        "NVARCHAR(10) -> NVARCHAR(20) with a unique index",
        "UQ",
        f"ALTER TABLE {TABLE} ALTER COLUMN UQ SET DATA TYPE NVARCHAR(20)",
        "unique",
    ),
    (
        "DECIMAL(5, 2) -> DECIMAL(7, 3)",
        "D",
        f"ALTER TABLE {TABLE} ALTER COLUMN D SET DATA TYPE DECIMAL(7, 3)",
        None,
    ),
    (
        "SET DEFAULT with a UX literal",
        "V",
        f"ALTER TABLE {TABLE} ALTER COLUMN V SET DEFAULT {_ux(DEFAULT_TEXT)}",
        "default",
    ),
    (
        "identity INTEGER -> BIGINT, SET DATA TYPE BIGINT",
        "ID",
        f"ALTER TABLE {TABLE} ALTER COLUMN ID SET DATA TYPE BIGINT",
        "identity",
    ),
    (
        "identity INTEGER -> BIGINT, with the identity clause",
        "ID",
        f"ALTER TABLE {TABLE} ALTER COLUMN ID SET DATA TYPE BIGINT "
        "GENERATED BY DEFAULT AS IDENTITY",
        "identity",
    ),
]


def connection_attributes(settings: Settings) -> dict[str, str]:
    import pyodbc

    pyodbc.pooling = False
    return BACKEND


def _drop_all(conn) -> None:
    _execute(conn, f"DROP INDEX {INDEX}")
    _execute(conn, f"DROP INDEX {UNIQUE}")
    _execute(conn, f"DROP TABLE {TABLE}")


def _fresh(conn) -> None:
    _drop_all(conn)
    for sql in SETUP:
        outcome = _execute(conn, sql)
        if outcome["result"] != "ok":
            raise RuntimeError(f"setup failed: {sql}: {outcome}")


def _describe(conn, column: str) -> dict[str, Any]:
    """The column as the driver describes it, and the values of all rows."""
    cursor = conn.cursor()
    try:
        cursor.execute(f"SELECT {column} FROM {TABLE} ORDER BY ID")
        rows = cursor.fetchall()
        _name, type_code, _display, size, precision, scale, nullable = cursor.description[0]
        return {
            "type": getattr(type_code, "__name__", str(type_code)),
            "size": size,
            "precision": precision,
            "scale": scale,
            "nullable": nullable,
            "values": [repr(row[0]) for row in rows],
        }
    except Exception as exc:  # recorded, the probe goes on
        return {"describe": "error", "message": str(exc)[:120]}
    finally:
        cursor.close()


def _check(conn, check: str | None) -> dict[str, Any]:
    if check == "index":
        return {
            "index objects": _rows(
                conn,
                "SELECT OBJNAME FROM TABLE(QSYS2.OBJECT_STATISTICS('QTEMP', '*FILE')) X "
                "WHERE OBJNAME = 'PACI'",
            )
        }
    if check == "unique":
        return {
            "duplicate insert": _execute(
                conn, f"INSERT INTO {TABLE} (IX, UQ) VALUES (3, 'a') WITH NC"
            ),
            "longer value insert": _execute(
                conn, f"INSERT INTO {TABLE} (IX, UQ) VALUES (4, 'fifteen chars..') WITH NC"
            ),
        }
    if check == "default":
        insert = _execute(conn, f"INSERT INTO {TABLE} (IX, UQ) VALUES (5, 'c') WITH NC")
        value = _rows(conn, f"SELECT V FROM {TABLE} WHERE IX = 5")
        return {
            "insert without V": insert,
            "V": value,
            "matches": bool(value) and value[0][0] == DEFAULT_TEXT,
            "expected": DEFAULT_TEXT,
        }
    if check == "identity":
        insert = _execute(conn, f"INSERT INTO {TABLE} (IX, UQ) VALUES (6, 'd') WITH NC")
        return {
            "insert without ID": insert,
            "IDs": _rows(conn, f"SELECT ID FROM {TABLE} ORDER BY ID"),
        }
    return {}


def run(settings: Settings, conn) -> dict[str, Any]:
    inquiry = _inquiry()
    cursor = conn.cursor()
    try:
        reply = inquiry.read_reply(cursor)
    finally:
        cursor.close()
    results: dict[str, Any] = {"inquiry message reply": reply}
    if reply != "*RQD":
        print(f"  the job's inquiry message reply is {reply}, not *RQD; nothing was run")
        return results
    try:
        for label, column, sql, check in CASES:
            _fresh(conn)
            outcome = _execute(conn, sql)
            outcome["job log"] = [row[0] for row in _rows(conn, JOB_LOG)]
            outcome["after"] = _describe(conn, column)
            outcome["check"] = _check(conn, check)
            results[label] = outcome
            print(f"\n  {label}")
            for key, value in outcome.items():
                print(f"    {key:<10} {value}")
    finally:
        _drop_all(conn)
    return results
