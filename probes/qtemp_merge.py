"""MERGE for bulk_create() with ignore_conflicts / update_conflicts (phase 5,
step B).

Writes only to QTEMP (tables that disappear with the job); reads nothing
outside it. Without commitment control (CMT=0): QTEMP tables have no
journal. Db2 for i has no INSERT ... ON CONFLICT; Django's hook only appends
a suffix to the INSERT, so the backend would have to write a MERGE instead:

    MERGE INTO t USING (VALUES (...), (...)) AS S (cols) ON <unique match>
    [WHEN MATCHED THEN UPDATE SET ...] WHEN NOT MATCHED THEN INSERT ...

Questions (each as one statement, its row count or SQLCODE recorded):

- parameter markers in the VALUES source: untyped, or CAST(? AS <type>);
- the ignore form (only WHEN NOT MATCHED) and the update form, and the row
  count each reports;
- a source with the same key twice (Django sends whatever the caller gives);
- ON over several unique keys with OR (ignore_conflicts has no target: any
  unique constraint, the primary key included);
- NOT ATOMIC CONTINUE ON SQLEXCEPTION (a duplicate in another unique key);
- SELECT ... FROM FINAL TABLE (MERGE ...), which update_conflicts with
  returned keys would need;
- a generated identity in the WHEN NOT MATCHED insert.

Usage (inside the "tests" container):
    nox -s probe -- merge

Findings go to docs/IBMI_NOTES.md.
"""

from __future__ import annotations

from typing import Any

from _common import Settings
from qtemp_alter_table import _execute
from qtemp_later_flags import _execute_error, _query, _step, connection_attributes  # noqa: F401

NEEDS_CONNECTION = True
AUTOCOMMIT = True

T = "QTEMP.PMRG"
# QTEMP takes no constraints (SQL7008), so the key is a unique index.
CREATE = (
    f"CREATE TABLE {T} (ID INTEGER GENERATED BY DEFAULT AS IDENTITY, "
    "K INTEGER NOT NULL, V VARCHAR(10), U INTEGER)"
)
# Unique keys besides the primary key: K, and U (nullable).
INDEXES = (
    f"CREATE UNIQUE INDEX QTEMP.PMRGID ON {T} (ID)",
    f"CREATE UNIQUE INDEX QTEMP.PMRGK ON {T} (K)",
    f"CREATE UNIQUE WHERE NOT NULL INDEX QTEMP.PMRGU ON {T} (U)",
)
SEED = f"INSERT INTO {T} (K, V, U) VALUES (1, 'one', 10), (2, 'two', 20)"

TYPED = "(CAST(? AS INTEGER), CAST(? AS VARCHAR(10)), CAST(? AS INTEGER))"
UNTYPED = "(?, ?, ?)"

IGNORE = (
    "MERGE INTO {t} AS T USING (VALUES {rows}) AS S (K, V, U) ON {on} "
    "WHEN NOT MATCHED THEN INSERT (K, V, U) VALUES (S.K, S.V, S.U)"
)
UPDATE = (
    "MERGE INTO {t} AS T USING (VALUES {rows}) AS S (K, V, U) ON {on} "
    "WHEN MATCHED THEN UPDATE SET V = S.V "
    "WHEN NOT MATCHED THEN INSERT (K, V, U) VALUES (S.K, S.V, S.U)"
)
ON_K = "T.K = S.K"
ON_ANY = "(T.K = S.K OR T.U = S.U)"


def _run(conn, sql: str, params=()) -> dict[str, Any]:
    """Execute one statement; its row count, or the error."""
    import pyodbc

    cursor = conn.cursor()
    try:
        cursor.execute(sql, params)
        return {"result": "ok", "rowcount": cursor.rowcount}
    except pyodbc.Error as exc:
        return {"result": "error", **_execute_error(exc)}
    finally:
        cursor.close()


def _rows(conn) -> list:
    outcome = _query(conn, f"SELECT K, V, U FROM {T} ORDER BY K")
    return outcome.get("rows", outcome)


def _fresh(conn) -> None:
    _execute(conn, f"DELETE FROM {T}")
    _execute(conn, SEED)


def _case(conn, results, key: str, sql: str, params=()) -> None:
    _fresh(conn)
    outcome = _run(conn, sql, params)
    if outcome["result"] == "ok":
        outcome["rows after"] = _rows(conn)
    _step(results, key, outcome)


def run(settings: Settings, conn) -> dict[str, Any]:
    results: dict[str, Any] = {"scope": "QTEMP only (tables gone with the job)"}
    _execute(conn, f"DROP TABLE {T}")
    if _step(results, "create", _execute(conn, CREATE))["result"] != "ok":
        return results
    for sql in INDEXES:
        _step(results, f"index: {sql.split(' ON ')[0]}", _execute(conn, sql))

    two = (2, "TWO", 20, 3, "three", 30)  # K=2 exists, K=3 is new
    print(" -- parameter markers in the source")
    rows = f"{UNTYPED}, {UNTYPED}"
    _case(conn, results, "ignore, untyped markers", IGNORE.format(t=T, rows=rows, on=ON_K), two)
    rows = f"{TYPED}, {TYPED}"
    _case(conn, results, "ignore, typed markers", IGNORE.format(t=T, rows=rows, on=ON_K), two)
    _case(conn, results, "update, typed markers", UPDATE.format(t=T, rows=rows, on=ON_K), two)

    print(" -- the same key twice in the source")
    twice = (4, "four", 40, 4, "FOUR", 41)
    _case(conn, results, "ignore, new key twice", IGNORE.format(t=T, rows=rows, on=ON_K), twice)
    _case(conn, results, "update, new key twice", UPDATE.format(t=T, rows=rows, on=ON_K), twice)
    existing_twice = (2, "TWO", 20, 2, "Two", 20)
    _case(
        conn,
        results,
        "update, existing key twice",
        UPDATE.format(t=T, rows=rows, on=ON_K),
        existing_twice,
    )

    print(" -- several unique keys")
    other_key = (5, "five", 10, 6, "six", 60)  # K=5 is new but U=10 exists
    _case(
        conn,
        results,
        "ignore, ON K only, conflict in U",
        IGNORE.format(t=T, rows=rows, on=ON_K),
        other_key,
    )
    _case(
        conn,
        results,
        "ignore, ON K OR U",
        IGNORE.format(t=T, rows=rows, on=ON_ANY),
        other_key,
    )
    null_u = (7, "seven", None, 8, "eight", None)
    _case(
        conn,
        results,
        "ignore, ON K OR U, NULL U twice",
        IGNORE.format(t=T, rows=rows, on=ON_ANY),
        null_u,
    )
    _case(
        conn,
        results,
        "ignore, ON K only, NOT ATOMIC CONTINUE ON SQLEXCEPTION",
        IGNORE.format(t=T, rows=rows, on=ON_K) + " NOT ATOMIC CONTINUE ON SQLEXCEPTION",
        other_key,
    )

    print(" -- returned rows")
    _fresh(conn)
    _step(
        results,
        "SELECT FROM FINAL TABLE (MERGE update)",
        _query(
            conn,
            "SELECT ID, K, V FROM FINAL TABLE (" + UPDATE.format(t=T, rows=rows, on=ON_K) + ")",
            two,
        ),
    )
    _step(
        results, "identities after the merges", _query(conn, f"SELECT ID, K FROM {T} ORDER BY ID")
    )
    _execute(conn, f"DROP TABLE {T}")
    return results
