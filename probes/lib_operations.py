"""Write probe 03: behaviour that DatabaseOperations depends on.

THIS CHANGES THE IBM i (two temporary tables). It is not part of probes/run.py.

Usage (on the host; bin/probe checks the approval on GitHub first):
    bin/probe --approved <link> lib_operations              # dry run: checks only
    bin/probe --approved <link> lib_operations -- --execute

Runs on DB2I_DEFAULT_LIBRARY (must have a QSQJRN journal) with the backend's
connection settings: NAM=0, CMT=1 (*CS), TRUEAUTOCOMMIT=1, autocommit on.

Tables (dropped at the end, always attempted):
    DJOPPAR (ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
             T TIME, TS TIMESTAMP(6))
    DJOPCHD (ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
             PARENT_ID INTEGER REFERENCES DJOPPAR (ID))

Sections:
1. TIME / TIMESTAMP fractional seconds (casts and columns).
2. IDENTITY_VAL_LOCAL() after single-row, multi-row, explicit-key and
   INSERT ... SELECT inserts, and its Python type.
3. Pagination: OFFSET without FETCH, OFFSET + FETCH FIRST, FETCH FIRST only.
4. TRUNCATE ... RESTART IDENTITY on a child table and on a parent table that
   is referenced by a foreign key (with and without IMMEDIATE, and inside a
   transaction), DELETE + ALTER ... RESTART as fallback, and whether the
   identity restarted.
"""

from __future__ import annotations

import argparse
import datetime as dt
import sys
from typing import Any

from _common import (
    ProbeError,
    Settings,
    connect,
    print_query,
    run_query,
    run_statement,
    run_values,
    write_result,
)

PARENT = "DJOPPAR"
CHILD = "DJOPCHD"
TIME_MICRO = dt.time(13, 45, 30, 123456)
TIMESTAMP_MICRO = dt.datetime(2026, 10, 17, 13, 45, 30, 123456)


def checks(conn, library: str) -> None:
    journal = run_query(
        conn,
        f"{library}: QSQJRN journal",
        "SELECT OBJNAME FROM TABLE(QSYS2.OBJECT_STATISTICS(?, '*JRN', 'QSQJRN')) X",
        (library,),
    )
    tables = run_query(
        conn,
        f"{library}: probe tables exist",
        "SELECT TABLE_NAME FROM QSYS2.SYSTABLES WHERE TABLE_SCHEMA = ? AND TABLE_NAME IN (?, ?)",
        (library, PARENT, CHILD),
    )
    for result in (journal, tables):
        print_query(result)
    if not journal["ok"] or not tables["ok"]:
        raise ProbeError("check", "pre-checks could not run; nothing was changed")
    if not journal["rows"]:
        raise ProbeError("check", f"{library} has no QSQJRN journal; run setup_journal first")
    if tables["rows"]:
        raise ProbeError("check", f"probe tables already exist in {library}; nothing was changed")


def section(title: str) -> None:
    print(f"\n{'=' * 8} {title} {'=' * 8}")


def run(conn, library: str) -> dict[str, Any]:
    parent, child = f"{library}.{PARENT}", f"{library}.{CHILD}"
    steps: list[dict[str, Any]] = []

    def stmt(label: str, sql: str, params: tuple = ()) -> dict[str, Any]:
        result = run_statement(conn, label, sql, params)
        steps.append(result)
        return result

    def vals(label: str, sql: str, params: tuple = ()) -> dict[str, Any]:
        result = run_values(conn, label, sql, params)
        steps.append(result)
        return result

    for label, sql in (
        (
            "create parent",
            f"CREATE TABLE {parent} (ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            "T TIME, TS TIMESTAMP(6))",
        ),
        (
            "create child",
            f"CREATE TABLE {child} (ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            f"PARENT_ID INTEGER REFERENCES {parent} (ID))",
        ),
    ):
        if not stmt(label, sql)["ok"]:
            stmt("drop parent (cleanup)", f"DROP TABLE {parent}")
            raise ProbeError("refused", f"{label} failed; probe tables cleaned up")

    try:
        section("1. TIME / TIMESTAMP fractional seconds")
        vals(
            "time: casts",
            "SELECT CAST(? AS TIME) AS T_PARAM, CAST(? AS TIMESTAMP) AS TS_PARAM, "
            "CAST('13.45.30' AS TIME) AS T_LITERAL FROM SYSIBM.SYSDUMMY1",
            (TIME_MICRO, TIMESTAMP_MICRO),
        )
        vals(
            "time: literal with fraction",
            "SELECT CAST('13.45.30.123456' AS TIME) AS T FROM SYSIBM.SYSDUMMY1",
        )
        stmt(
            "time: insert columns",
            f"INSERT INTO {parent} (T, TS) VALUES (?, ?)",
            (TIME_MICRO, TIMESTAMP_MICRO),
        )
        vals("time: read columns", f"SELECT ID, T, TS, CHAR(T) AS T_CHAR FROM {parent}")

        section("2. IDENTITY_VAL_LOCAL()")
        identity = f"SELECT IDENTITY_VAL_LOCAL() AS ID {'FROM SYSIBM.SYSDUMMY1'}"
        vals("identity after single-row insert", identity)
        stmt("insert single row", f"INSERT INTO {parent} (T) VALUES (NULL)")
        vals("identity after single-row insert (2)", identity)
        stmt("insert multi-row", f"INSERT INTO {parent} (T) VALUES (NULL), (NULL)")
        vals("identity after multi-row insert", identity)
        stmt("insert explicit key 100", f"INSERT INTO {parent} (ID, T) VALUES (100, NULL)")
        vals("identity after explicit-key insert", identity)
        stmt(
            "insert ... select",
            f"INSERT INTO {parent} (T) SELECT CAST(NULL AS TIME) FROM SYSIBM.SYSDUMMY1",
        )
        vals("identity after insert ... select", identity)
        vals("parent rows", f"SELECT ID FROM {parent} ORDER BY ID")

        section("3. Pagination")
        vals("offset only", f"SELECT ID FROM {parent} ORDER BY ID OFFSET 2 ROWS")
        vals(
            "offset + fetch first",
            f"SELECT ID FROM {parent} ORDER BY ID OFFSET 1 ROWS FETCH FIRST 2 ROWS ONLY",
        )
        vals("fetch first only", f"SELECT ID FROM {parent} ORDER BY ID FETCH FIRST 2 ROWS ONLY")

        section("4. TRUNCATE / identity restart")
        stmt("insert child", f"INSERT INTO {child} (PARENT_ID) VALUES (1)")
        stmt("truncate child restart identity", f"TRUNCATE TABLE {child} RESTART IDENTITY")
        vals("child rows after truncate", f"SELECT COUNT(*) AS N FROM {child}")
        stmt("truncate referenced parent", f"TRUNCATE TABLE {parent} RESTART IDENTITY")
        stmt(
            "truncate referenced parent immediate",
            f"TRUNCATE TABLE {parent} RESTART IDENTITY IMMEDIATE",
        )
        vals("parent rows after truncate attempts", f"SELECT COUNT(*) AS N FROM {parent}")

        conn.autocommit = False
        stmt("truncate child in transaction", f"TRUNCATE TABLE {child} RESTART IDENTITY")
        conn.rollback()
        conn.autocommit = True

        stmt("fallback: delete parent", f"DELETE FROM {parent}")
        stmt(
            "fallback: restart identity",
            f"ALTER TABLE {parent} ALTER COLUMN ID RESTART WITH 1",
        )
        stmt("insert after restart", f"INSERT INTO {parent} (T) VALUES (NULL)")
        vals("parent ids after restart", f"SELECT ID FROM {parent} ORDER BY ID")
        stmt("insert child after restart", f"INSERT INTO {child} (PARENT_ID) VALUES (1)")
        vals("child ids after truncate restart", f"SELECT ID FROM {child} ORDER BY ID")
    finally:
        conn.autocommit = True
        for table in (child, parent):
            if not stmt(f"drop {table}", f"DROP TABLE {table}")["ok"]:
                print(f"\nWARNING: {table} was NOT dropped; remove it manually.", file=sys.stderr)

    print("\nSummary")
    for result in steps:
        state = "ok" if result["ok"] else f"{result['sqlstate']} {result['message'][:110]}"
        print(f"  {result['label']:<40} {state}")
    return {"steps": steps}


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--execute", action="store_true", help="create, use and drop the tables")
    args = parser.parse_args(argv)

    conn = None
    try:
        settings = Settings.from_env(need_credentials=True)
        library = settings.default_library
        if not library:
            raise ProbeError("config", "DB2I_DEFAULT_LIBRARY is not set", 1)
        conn = connect(settings, {"CMT": "1", "TRUEAUTOCOMMIT": "1"}, autocommit=True)
        checks(conn, library)
        if not args.execute:
            print("\nDry run: nothing was changed. Re-run with --execute to apply.")
            return 0
        result = run(conn, library)
        print(f"\nresult saved to {write_result('lib_operations', result, settings)}")
    except ProbeError as exc:
        print(f"\nPROBE FAILED [{exc.category}]: {exc}", file=sys.stderr)
        return exc.exit_code
    finally:
        if conn is not None:
            conn.close()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
