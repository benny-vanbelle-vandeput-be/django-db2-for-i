"""Write probe 04: SEQUENCE objects as an alternative to identity columns.

THIS CHANGES THE IBM i (one sequence, two temporary tables). Not part of
probes/run.py.

Usage (on the host; bin/probe checks the approval on GitHub first):
    bin/probe --approved <link> lib_sequence              # dry run: checks only
    bin/probe --approved <link> lib_sequence -- --execute

Question: can an AutoField be backed by a SEQUENCE (column DEFAULT NEXT VALUE
FOR ...), so that the key generator can be restarted inside a transaction
that has pending row changes on the table (as in Django's TestCase after
loading fixtures), where ALTER TABLE ... RESTART fails with SQL0910?

On DB2I_DEFAULT_LIBRARY (journaled), one connection, backend settings
(NAM=0, CMT=1, TRUEAUTOCOMMIT=1):

1. CREATE SEQUENCE DJSEQ; CREATE TABLE DJSEQT with ID DEFAULT NEXT VALUE FOR
   DJSEQ; identity table DJSEQI as baseline.
2. Baseline: in a transaction, INSERT into DJSEQI, then ALTER TABLE ...
   RESTART (expected SQL0910). Rollback.
3. In a transaction on DJSEQT: generated and explicit inserts, PREVIOUS VALUE
   FOR, ALTER SEQUENCE ... RESTART WITH (SQL0910 or not), insert after the
   restart. Rollback, then check what the rollback undid (rows, sequence).
4. Autocommit: multi-row insert and PREVIOUS VALUE FOR; inserting with an
   explicit NEXT VALUE FOR expression (if the DEFAULT is not supported).
5. Drop everything (always attempted).
"""

from __future__ import annotations

import argparse
import sys
from typing import Any

from _common import (
    ProbeError,
    Settings,
    connect,
    print_query,
    run_query,
    run_statement,
    run_values,
    write_result,
)

SEQUENCE = "DJSEQ"
SEQ_TABLE = "DJSEQT"
IDENTITY_TABLE = "DJSEQI"


def checks(conn, library: str) -> None:
    journal = run_query(
        conn,
        f"{library}: QSQJRN journal",
        "SELECT OBJNAME FROM TABLE(QSYS2.OBJECT_STATISTICS(?, '*JRN', 'QSQJRN')) X",
        (library,),
    )
    existing = run_query(
        conn,
        f"{library}: probe objects exist",
        "SELECT OBJNAME, OBJTYPE FROM TABLE(QSYS2.OBJECT_STATISTICS(?, '*FILE *DTAARA')) X "
        "WHERE OBJNAME IN (?, ?, ?)",
        (library, SEQUENCE, SEQ_TABLE, IDENTITY_TABLE),
    )
    for result in (journal, existing):
        print_query(result)
    if not journal["ok"] or not existing["ok"]:
        raise ProbeError("check", "pre-checks could not run; nothing was changed")
    if not journal["rows"]:
        raise ProbeError("check", f"{library} has no QSQJRN journal; run setup_journal first")
    if existing["rows"]:
        raise ProbeError("check", f"probe objects already exist in {library}; nothing was changed")


def run(conn, library: str) -> dict[str, Any]:
    seq, table, identity = (f"{library}.{name}" for name in (SEQUENCE, SEQ_TABLE, IDENTITY_TABLE))
    steps: list[dict[str, Any]] = []
    created: list[tuple[str, str]] = []

    def stmt(label: str, sql: str, params: tuple = ()) -> dict[str, Any]:
        result = run_statement(conn, label, sql, params)
        steps.append(result)
        return result

    def vals(label: str, sql: str, params: tuple = ()) -> dict[str, Any]:
        result = run_values(conn, label, sql, params)
        steps.append(result)
        return result

    previous = f"SELECT PREVIOUS VALUE FOR {seq} AS PREV FROM SYSIBM.SYSDUMMY1"
    try:
        print("\n======== 1. Objects ========")
        if not stmt("create sequence", f"CREATE SEQUENCE {seq} AS INTEGER START WITH 1")["ok"]:
            raise ProbeError("refused", "CREATE SEQUENCE failed; nothing else was run")
        created.append(("SEQUENCE", seq))
        default_ok = stmt(
            "create table with DEFAULT NEXT VALUE FOR",
            f"CREATE TABLE {table} (ID INTEGER NOT NULL DEFAULT NEXT VALUE FOR {seq} "
            "PRIMARY KEY, V INTEGER)",
        )["ok"]
        # Without DEFAULT support, fall back to a plain key column.
        if (
            default_ok
            or stmt(
                "create table without default (fallback)",
                f"CREATE TABLE {table} (ID INTEGER NOT NULL PRIMARY KEY, V INTEGER)",
            )["ok"]
        ):
            created.append(("TABLE", table))
        if stmt(
            "create identity table (baseline)",
            f"CREATE TABLE {identity} (ID INTEGER GENERATED BY DEFAULT AS IDENTITY "
            "PRIMARY KEY, V INTEGER)",
        )["ok"]:
            created.append(("TABLE", identity))

        generated = (
            f"INSERT INTO {table} (V) VALUES (?)"
            if default_ok
            else f"INSERT INTO {table} (ID, V) VALUES (NEXT VALUE FOR {seq}, ?)"
        )

        print("\n======== 2. Baseline: identity restart in a transaction ========")
        conn.autocommit = False
        stmt("identity: insert in transaction", f"INSERT INTO {identity} (V) VALUES (1)")
        stmt(
            "identity: ALTER TABLE RESTART in same transaction",
            f"ALTER TABLE {identity} ALTER COLUMN ID RESTART WITH 50",
        )
        conn.rollback()

        print("\n======== 3. Sequence restart in a transaction ========")
        stmt("seq: generated insert", generated, (1,))
        vals("seq: PREVIOUS VALUE FOR after generated insert", previous)
        stmt("seq: explicit key 100", f"INSERT INTO {table} (ID, V) VALUES (100, 2)")
        vals("seq: PREVIOUS VALUE FOR after explicit insert", previous)
        stmt(
            "seq: ALTER SEQUENCE RESTART in same transaction",
            f"ALTER SEQUENCE {seq} RESTART WITH 101",
        )
        stmt("seq: generated insert after restart", generated, (3,))
        vals("seq: PREVIOUS VALUE FOR after restart", previous)
        vals("seq: rows in transaction", f"SELECT ID, V FROM {table} ORDER BY ID")
        conn.rollback()
        conn.autocommit = True
        vals("seq: rows after rollback", f"SELECT ID, V FROM {table} ORDER BY ID")
        stmt("seq: generated insert after rollback", generated, (4,))
        vals(
            "seq: rows after rollback + insert (was the restart undone?)",
            f"SELECT ID, V FROM {table} ORDER BY ID",
        )

        print("\n======== 4. Autocommit ========")
        if default_ok:
            stmt("seq: multi-row insert", f"INSERT INTO {table} (V) VALUES (5), (6)")
        else:
            stmt(
                "seq: multi-row insert",
                f"INSERT INTO {table} (ID, V) VALUES (NEXT VALUE FOR {seq}, 5), "
                f"(NEXT VALUE FOR {seq}, 6)",
            )
        vals("seq: PREVIOUS VALUE FOR after multi-row insert", previous)
        vals("seq: final rows", f"SELECT ID, V FROM {table} ORDER BY ID")
        vals(
            "seq: catalog (QSYS2.SYSSEQUENCES)",
            "SELECT SEQUENCE_NAME, DATA_TYPE, START, INCREMENT, CACHE, CYCLE, ORDER "
            "FROM QSYS2.SYSSEQUENCES WHERE SEQUENCE_SCHEMA = ? AND SEQUENCE_NAME = ?",
            (library, SEQUENCE),
        )
    finally:
        conn.autocommit = True
        for kind, name in reversed(created):
            if not stmt(f"drop {name}", f"DROP {kind} {name}")["ok"]:
                print(
                    f"\nWARNING: {kind} {name} was NOT dropped; remove it manually.",
                    file=sys.stderr,
                )

    print("\nSummary")
    for result in steps:
        state = "ok" if result["ok"] else f"{result['sqlstate']} {result['message'][:100]}"
        print(f"  {result['label'][:60]:<60} {state}")
    return {"steps": steps, "default_next_value_supported": default_ok}


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--execute", action="store_true", help="create, use and drop the objects")
    args = parser.parse_args(argv)

    conn = None
    try:
        settings = Settings.from_env(need_credentials=True)
        library = settings.default_library
        if not library:
            raise ProbeError("config", "DB2I_DEFAULT_LIBRARY is not set", 1)
        conn = connect(settings, {"CMT": "1", "TRUEAUTOCOMMIT": "1"}, autocommit=True)
        checks(conn, library)
        if not args.execute:
            print("\nDry run: nothing was changed. Re-run with --execute to apply.")
            return 0
        result = run(conn, library)
        print(f"\nresult saved to {write_result('lib_sequence', result, settings)}")
    except ProbeError as exc:
        print(f"\nPROBE FAILED [{exc.category}]: {exc}", file=sys.stderr)
        return exc.exit_code
    finally:
        if conn is not None:
            conn.close()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
