"""Column renames and identity changes, in QTEMP (phase 4, step C item 8).

Writes only to QTEMP (tables that disappear with the job). Like probe 24
(qtemp_alter_table) it changes no job attribute and runs only when the job's
inquiry message reply is *RQD, so a statement that sends CPA32B2 is cancelled
(HY008) and changes nothing.

Every case runs on a fresh two-row table and records the outcome (SQLSTATE,
SQLCODE, message), the last job log messages and a check afterwards:

- every candidate form for renaming a column (Db2 for i's SQL reference for
  7.6 lists none; the SQLCODE of each form is recorded);
- the identity changes as Django writes them (schema editor SQL):
  AutoField -> IntegerField (SET DATA TYPE INTEGER on an identity column)
  and the alternative DROP IDENTITY; IntegerField -> AutoField on a column
  with rows (SET DATA TYPE ... GENERATED BY DEFAULT AS IDENTITY: where does
  the numbering start? RESTART WITH a constant, or a dynamic compound
  statement that reads MAX(ID) itself); SmallAutoField -> AutoField and BigAutoField ->
  AutoField.

Findings go to docs/IBMI_NOTES.md.
"""

from __future__ import annotations

from typing import Any

from _common import Settings
from qtemp_alter_table import BACKEND, JOB_LOG, _execute, _inquiry, _rows

NEEDS_CONNECTION = True
AUTOCOMMIT = True

TABLE = "QTEMP.PRNT"
# A unique index stands in for the primary key: QTEMP takes no constraints
# under commitment control (SQL7008, qtemp_alter_column). It shows collisions.
UNIQUE = f"CREATE UNIQUE INDEX QTEMP.PRNI ON {TABLE} (ID)"
PLAIN = (
    f"CREATE TABLE {TABLE} (ID INTEGER NOT NULL, A INTEGER)",
    UNIQUE,
    f"INSERT INTO {TABLE} (ID, A) VALUES (1, 10), (2, 20) WITH NC",
)


def _identity(sql_type: str) -> tuple[str, ...]:
    return (
        f"CREATE TABLE {TABLE} (ID {sql_type} GENERATED BY DEFAULT AS IDENTITY "
        "NOT NULL, A INTEGER)",
        UNIQUE,
        f"INSERT INTO {TABLE} (A) VALUES (10), (20) WITH NC",
    )


# (label, setup, statement, check)
CASES = [
    ("RENAME COLUMN in ALTER TABLE", PLAIN, f"ALTER TABLE {TABLE} RENAME COLUMN A TO B", "B"),
    ("RENAME COLUMN statement", PLAIN, f"RENAME COLUMN {TABLE}.A TO B", "B"),
    ("ALTER COLUMN ... RENAME TO", PLAIN, f"ALTER TABLE {TABLE} ALTER COLUMN A RENAME TO B", "B"),
    ("RENAME <table>.<column>", PLAIN, f"RENAME {TABLE}.A TO B", "B"),
    (
        "AutoField -> IntegerField as Django writes it (SET DATA TYPE INTEGER)",
        _identity("INTEGER"),
        f"ALTER TABLE {TABLE} ALTER COLUMN ID SET DATA TYPE INTEGER",
        "explicit id",
    ),
    (
        "AutoField -> IntegerField with DROP IDENTITY",
        _identity("INTEGER"),
        f"ALTER TABLE {TABLE} ALTER COLUMN ID DROP IDENTITY",
        "explicit id",
    ),
    (
        "IntegerField -> AutoField on a column with rows",
        PLAIN,
        f"ALTER TABLE {TABLE} ALTER COLUMN ID SET DATA TYPE INTEGER "
        "GENERATED BY DEFAULT AS IDENTITY",
        "generated id",
    ),
    (
        "IntegerField -> AutoField, then RESTART WITH 3",
        PLAIN,
        f"ALTER TABLE {TABLE} ALTER COLUMN ID SET DATA TYPE INTEGER "
        "GENERATED BY DEFAULT AS IDENTITY",
        "restart",
    ),
    (
        "IntegerField -> AutoField, then a compound statement restarts at MAX + 1",
        PLAIN,
        f"ALTER TABLE {TABLE} ALTER COLUMN ID SET DATA TYPE INTEGER "
        "GENERATED BY DEFAULT AS IDENTITY",
        "compound",
    ),
    (
        "SmallAutoField -> AutoField",
        _identity("SMALLINT"),
        f"ALTER TABLE {TABLE} ALTER COLUMN ID SET DATA TYPE INTEGER "
        "GENERATED BY DEFAULT AS IDENTITY",
        "generated id",
    ),
    (
        "BigAutoField -> AutoField (narrowing)",
        _identity("BIGINT"),
        f"ALTER TABLE {TABLE} ALTER COLUMN ID SET DATA TYPE INTEGER "
        "GENERATED BY DEFAULT AS IDENTITY",
        "generated id",
    ),
]


def connection_attributes(settings: Settings) -> dict[str, str]:
    import pyodbc

    pyodbc.pooling = False
    return BACKEND


def _fresh(conn, setup: tuple[str, ...]) -> None:
    _execute(conn, f"DROP TABLE {TABLE}")
    for sql in setup:
        outcome = _execute(conn, sql)
        if outcome["result"] != "ok":
            raise RuntimeError(f"setup failed: {sql}: {outcome}")


def _identity_state(conn) -> list:
    return _rows(
        conn,
        "SELECT IS_IDENTITY, IDENTITY_GENERATION, IS_NULLABLE, DATA_TYPE "
        "FROM QSYS2.SYSCOLUMNS WHERE TABLE_SCHEMA = 'QTEMP' AND TABLE_NAME = 'PRNT' "
        "AND COLUMN_NAME = 'ID'",
    )


def _check(conn, check: str) -> dict[str, Any]:
    if check == "B":
        return {"select B": _execute(conn, f"SELECT B FROM {TABLE}")}
    if check == "explicit id":
        return {
            "insert with ID": _execute(conn, f"INSERT INTO {TABLE} (ID, A) VALUES (5, 50) WITH NC"),
            "insert without ID": _execute(conn, f"INSERT INTO {TABLE} (A) VALUES (60) WITH NC"),
            "IDs": _rows(conn, f"SELECT ID FROM {TABLE} ORDER BY ID"),
            # Catalog rows of QTEMP tables are not visible (probe 25); kept as a record.
            "catalog": _identity_state(conn),
        }
    if check == "generated id":
        return {
            "insert without ID": _execute(conn, f"INSERT INTO {TABLE} (A) VALUES (30) WITH NC"),
            "IDs": _rows(conn, f"SELECT ID FROM {TABLE} ORDER BY ID"),
        }
    if check == "compound":
        compound = _execute(
            conn,
            "BEGIN DECLARE NEXT_ID BIGINT; "
            f"SET NEXT_ID = (SELECT COALESCE(MAX(ID), 0) + 1 FROM {TABLE}); "
            f"EXECUTE IMMEDIATE 'ALTER TABLE {TABLE} ALTER COLUMN ID RESTART WITH ' "
            "CONCAT VARCHAR(NEXT_ID); END",
        )
        return {
            "compound": compound,
            "insert without ID": _execute(conn, f"INSERT INTO {TABLE} (A) VALUES (30) WITH NC"),
            "IDs": _rows(conn, f"SELECT ID FROM {TABLE} ORDER BY ID"),
        }
    if check == "restart":
        restart = _execute(conn, f"ALTER TABLE {TABLE} ALTER COLUMN ID RESTART WITH 3")
        return {
            "restart": restart,
            "insert without ID": _execute(conn, f"INSERT INTO {TABLE} (A) VALUES (30) WITH NC"),
            "IDs": _rows(conn, f"SELECT ID FROM {TABLE} ORDER BY ID"),
        }
    return {}


def run(settings: Settings, conn) -> dict[str, Any]:
    inquiry = _inquiry()
    cursor = conn.cursor()
    try:
        reply = inquiry.read_reply(cursor)
    finally:
        cursor.close()
    results: dict[str, Any] = {"inquiry message reply": reply}
    if reply != "*RQD":
        print(f"  the job's inquiry message reply is {reply}, not *RQD; nothing was run")
        return results
    try:
        for label, setup, sql, check in CASES:
            _fresh(conn, setup)
            outcome = _execute(conn, sql)
            outcome["job log"] = [row[0] for row in _rows(conn, JOB_LOG)]
            outcome["check"] = _check(conn, check)
            results[label] = outcome
            print(f"\n  {label}")
            for key, value in outcome.items():
                print(f"    {key:<10} {value}")
    finally:
        _execute(conn, f"DROP TABLE {TABLE}")
    return results
