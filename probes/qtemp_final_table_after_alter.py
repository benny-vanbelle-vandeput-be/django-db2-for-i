"""A repeated statement after a column grows (found by Django's *_foreignfield_growth).

``migrations.test_operations...test_autofield__bigautofield_foreignfield_growth``
inserts with one SQL text, widens the column, and sends the same text again with a
value that needs the new type: HY019 "Numeric value out of range" from the driver,
since returning columns (phase 5, step A1). This finds out what it depends on:
FINAL TABLE or any statement, the same text or a new one, other column types (a longer
string: refused, or silently cut off?), and what clears it.

Writes only to QTEMP (tables that disappear with the job); reads nothing outside it.
Without commitment control (CMT=0): QTEMP tables have no journal. One connection,
no retries.

Usage (inside the "tests" container):
    nox -s probe -- final_table_after_alter

Findings go to docs/IBMI_NOTES.md.
"""

from __future__ import annotations

from decimal import Decimal
from typing import Any

from _common import Settings
from qtemp_alter_table import _execute
from qtemp_later_flags import _query, _step, connection_attributes  # noqa: F401

NEEDS_CONNECTION = True
AUTOCOMMIT = True

TABLE = "QTEMP.P5GROW"
BIG = 2**33
ALTER = f"ALTER TABLE {TABLE} ALTER COLUMN I SET DATA TYPE BIGINT"
INSERT = f"INSERT INTO {TABLE} (I) VALUES (?)"
FINAL = f"SELECT ID FROM FINAL TABLE ({INSERT})"


def final(case: str) -> str:
    """Its own text per case: the first prepare of a text on a connection decides the
    parameter types of that text from then on, also after DROP and CREATE."""
    return f"SELECT ID AS {case} FROM FINAL TABLE ({INSERT})"


# name, the statement before the ALTER (None: not sent), the statement after it,
# whether it is a query.
CASES = (
    ("FINAL TABLE, only sent after the ALTER", None, final("A"), True),
    ("plain INSERT, the same text", INSERT, INSERT, False),
    ("FINAL TABLE, the same text", final("B"), final("B"), True),
    ("FINAL TABLE, a trailing space after", final("C"), final("C") + " ", True),
    ("FINAL TABLE, a line comment after", final("D"), f"{final('D')} -- 1\n", True),
    (
        "FINAL TABLE, a typed marker both times",
        f"SELECT ID AS E FROM FINAL TABLE (INSERT INTO {TABLE} (I) VALUES (CAST(? AS BIGINT)))",
        f"SELECT ID AS E FROM FINAL TABLE (INSERT INTO {TABLE} (I) VALUES (CAST(? AS BIGINT)))",
        True,
    ),
    (
        "UPDATE, the same text",
        f"UPDATE {TABLE} SET I = ? WHERE ID = 0",
        f"UPDATE {TABLE} SET I = ? WHERE ID = 0",
        False,
    ),
    (
        "SELECT with the column compared, the same text",
        f"SELECT ID FROM {TABLE} WHERE I = ?",
        f"SELECT ID FROM {TABLE} WHERE I = ?",
        True,
    ),
)


def _send(conn, sql: str, value: Any, query: bool) -> dict[str, Any]:
    outcome = _query(conn, sql, (value,)) if query else _execute(conn, sql, (value,))
    return {k: outcome.get(k) for k in ("result", "sqlstate", "sqlcode", "message", "rows")}


def _fresh(conn, columns: str) -> bool:
    _execute(conn, f"DROP TABLE {TABLE}")
    return _execute(conn, f"CREATE TABLE {TABLE} ({columns})")["result"] == "ok"


def _types(conn, results) -> None:
    """Other columns that grow: is a longer value refused, or silently cut off?"""
    identity = "ID INTEGER GENERATED BY DEFAULT AS IDENTITY"
    for key, column, altered, small, big in (
        ("NVARCHAR(10) to NVARCHAR(100)", "NVARCHAR(10)", "NVARCHAR(100)", "short", "x" * 50),
        ("VARCHAR(10) to VARCHAR(100)", "VARCHAR(10)", "VARCHAR(100)", "short", "y" * 50),
        (
            "DECIMAL(5, 2) to DECIMAL(12, 2)",
            "DECIMAL(5, 2)",
            "DECIMAL(12, 2)",
            Decimal("1.50"),
            Decimal("1234567.25"),
        ),
        (
            "DECIMAL(5, 2) to DECIMAL(9, 4)",
            "DECIMAL(5, 2)",
            "DECIMAL(9, 4)",
            Decimal("1.50"),
            Decimal("1.2345"),
        ),
    ):
        outcome: dict[str, Any] = {}
        if not _fresh(conn, f"{identity}, V {column}"):
            _step(results, key, {"create": "refused"})
            continue
        name = "".join(c for c in key if c.isalnum())
        insert = f"SELECT ID AS {name[:20]} FROM FINAL TABLE (INSERT INTO {TABLE} (V) VALUES (?))"
        outcome["before the ALTER"] = _send(conn, insert, small, True)
        if column.endswith("(10)"):
            _send(conn, f"INSERT INTO {TABLE} (V) VALUES (?) -- {name}\n", small, False)
            _send(conn, f"UPDATE {TABLE} SET V = ? WHERE ID = 0 -- {name}\n", small, False)
        outcome["ALTER"] = _execute(
            conn, f"ALTER TABLE {TABLE} ALTER COLUMN V SET DATA TYPE {altered}"
        )
        outcome["after it, the longer value"] = _send(conn, insert, big, True)
        outcome["read back"] = _query(conn, f"SELECT V, LENGTH(V) FROM {TABLE} ORDER BY ID").get(
            "rows"
        )
        outcome["expected"] = repr(big)
        if column.endswith("(10)"):
            plain = f"INSERT INTO {TABLE} (V) VALUES (?) -- {name}\n"
            outcome["the same plain INSERT, the longer value"] = _send(conn, plain, big, False)
            update = f"UPDATE {TABLE} SET V = ? WHERE ID = 0 -- {name}\n"
            outcome["the same UPDATE, the longer value"] = _send(conn, update, big, False)
        _step(results, key, outcome)


def _resets(conn, results) -> None:
    """What clears it: a commit, a rollback, a closed cursor, another statement?"""
    columns = "ID INTEGER GENERATED BY DEFAULT AS IDENTITY, I INTEGER"
    for number, (key, action) in enumerate(
        (
            ("nothing in between (the control)", lambda: None),
            ("after a commit", lambda: conn.commit()),
            ("after a rollback", lambda: conn.rollback()),
            ("after a plain INSERT of the big value", lambda: _execute(conn, INSERT, (BIG,))),
            ("after a query without parameters", lambda: _query(conn, f"SELECT ID FROM {TABLE}")),
            ("after DROP and CREATE, the column already wide", None),
            ("after a closed and new cursor, explicitly", lambda: conn.cursor().close()),
        )
    ):
        text = final(f"R{number}")
        outcome: dict[str, Any] = {}
        if not _fresh(conn, columns):
            continue
        outcome["before the ALTER"] = _send(conn, text, 1, True)
        if action is None:
            wide = "ID INTEGER GENERATED BY DEFAULT AS IDENTITY, I BIGINT"
            outcome["recreated"] = _fresh(conn, wide)
        else:
            outcome["ALTER"] = _execute(conn, ALTER)
            action()
        outcome["after it, a big value"] = _send(conn, text, BIG, True)
        _step(results, key, outcome)


def run(settings: Settings, conn) -> dict[str, Any]:
    results: dict[str, Any] = {"scope": "QTEMP only (tables gone with the job)"}
    for key, before, after, query in CASES:
        _execute(conn, f"DROP TABLE {TABLE}")
        created = _execute(
            conn,
            f"CREATE TABLE {TABLE} (ID INTEGER GENERATED BY DEFAULT AS IDENTITY, I INTEGER)",
        )
        if created["result"] != "ok":
            _step(results, key, {"create": created})
            continue
        outcome: dict[str, Any] = {}
        if before:
            outcome["before the ALTER, a small value"] = _send(conn, before, 1, query)
            outcome["before the ALTER, again"] = _send(conn, before, 2, query)
        outcome["ALTER"] = _execute(conn, ALTER)
        outcome["after it, a small value"] = _send(conn, after, 3, query)
        outcome["after it, a big value"] = _send(conn, after, BIG, query)
        outcome["again, a big value"] = _send(conn, after, BIG + 1, query)
        _step(results, key, outcome)
    _execute(conn, f"DROP TABLE {TABLE}")
    _types(conn, results)
    _resets(conn, results)
    _execute(conn, f"DROP TABLE {TABLE}")
    return results
