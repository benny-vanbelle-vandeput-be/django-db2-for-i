"""Which DDL a ROLLBACK undoes under commitment control (phase 4, step C item 11a).

THIS CHANGES THE IBM i: tables with the prefix DJ11A (DJ11AT, the table under
test; DJ11AP, a parent table for a foreign key; DJ11AH, a helper table) in
the journaled default library, with the indexes DJ11AI / DJ11AJ / DJ11AU and
the constraints DJ11A_UQ / DJ11A_CK / DJ11A_FK on DJ11AT, and one temporary
rename DJ11AT -> DJ11AR. Every table is recorded on the cleanup list
(tests/table_registry.py) before its CREATE TABLE, the rename through the
list's renamed_from (#148); all of it is dropped at the end, also after a
failure. Approved by the maintainer on 2026-10-24 on issue #149 under these
conditions: only its own prefixed tables in the journaled default library;
always cleaned up, also on failure; nothing else read or changed; one
connection through the lock; started via bin/probe --approved <link>. Not
part of probes/run.py.

Usage (on the host; bin/probe checks the approval on GitHub first):
    bin/probe --approved <link> lib_rollback_ddl              # dry run: checks only
    bin/probe --approved <link> lib_rollback_ddl -- --execute

Each case starts from a fresh DJ11AT (two rows), then, with autocommit off:
inserts a row into DJ11AH (an implicit commit would keep it), runs the DDL in
the form the schema editor writes it, and rolls back. It records each
statement's outcome, whether the DDL is undone (catalog) and whether the
DJ11AH row is gone. The job's inquiry message reply must be *RQD, so a
statement that sends CPA32B2 is cancelled; the probe changes no job
attribute. Every catalog query is limited to the probe's own objects.
"""

from __future__ import annotations

import argparse
import contextlib
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any

from _common import (
    ProbeError,
    Settings,
    connect,
    print_query,
    run_query,
    run_statement,
    write_result,
)

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from django_db2_for_i import inquiry
from tests import table_registry

T, P, H, R = "DJ11AT", "DJ11AP", "DJ11AH", "DJ11AR"
TABLES = (T, R, P, H)  # drop order
PROBE_OBJECTS = (
    "SELECT OBJNAME FROM TABLE(QSYS2.OBJECT_STATISTICS(?, '*FILE')) X WHERE OBJNAME LIKE 'DJ11A%'"
)
T_BODY = (
    "ID INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "
    "A INTEGER NOT NULL DEFAULT 0, V NVARCHAR(20), N INTEGER"
)


class Probe:
    def __init__(self, conn, library: str):
        self.conn = conn
        self.library = library
        self.registry = table_registry.list_path()
        self.steps: list[dict[str, Any]] = []

    # --- helpers ------------------------------------------------------------------

    def q(self, name: str) -> str:
        return f"{self.library}.{name}"

    def run(self, label: str, sql: str) -> dict[str, Any]:
        result = run_statement(self.conn, label, sql)
        self.steps.append(result)
        return result

    def scalar(self, sql: str, params: tuple = ()) -> Any:
        result = run_query(self.conn, "check", sql, params)
        if not result["ok"]:
            return f"error {result.get('sqlstate')}"
        rows = result["rows"]
        return next(iter(rows[0].values())) if rows else None

    def create(self, name: str, body: str) -> dict[str, Any]:
        sql = f"CREATE TABLE {self.q(name)} ({body})"
        entry = table_registry.parse(sql, self.library)
        assert entry is not None and entry.name == name
        table_registry.record(self.registry, entry)
        return self.run(f"create {name}", sql)

    def exists(self, name: str) -> bool:
        return bool(
            self.scalar(
                "SELECT COUNT(*) FROM QSYS2.SYSTABLES WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ?",
                (self.library, name),
            )
        )

    def column(self, name: str, attribute: str) -> Any:
        return self.scalar(
            f"SELECT {attribute} FROM QSYS2.SYSCOLUMNS "
            "WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? AND COLUMN_NAME = ?",
            (self.library, T, name),
        )

    def index_exists(self, name: str) -> bool:
        return bool(
            self.scalar(
                "SELECT COUNT(*) FROM QSYS2.SYSINDEXES WHERE INDEX_SCHEMA = ? AND INDEX_NAME = ?",
                (self.library, name),
            )
        )

    def constraint_exists(self, name: str) -> bool:
        return bool(
            self.scalar(
                "SELECT COUNT(*) FROM QSYS2.SYSCST "
                "WHERE CONSTRAINT_SCHEMA = ? AND CONSTRAINT_NAME = ?",
                (self.library, name),
            )
        )

    def fresh(self) -> None:
        """A fresh DJ11AT with two rows (N = 1 and N = NULL), autocommit on."""
        self.conn.autocommit = True
        for name in (T, R):
            if self.exists(name):
                self.run(f"drop {name}", f"DROP TABLE {self.q(name)}")
        if not self.create(T, T_BODY)["ok"]:
            raise ProbeError("refused", f"create {T} failed")
        self.run(
            "rows",
            f"INSERT INTO {self.q(T)} (A, V, N) VALUES (1, 'a', 1), (2, 'b', NULL)",
        )

    # --- one case -----------------------------------------------------------------

    def case(
        self,
        number: int,
        label: str,
        statements: list[str],
        check: Callable[[], dict[str, Any]],
        setup: list[str] = (),
        before_each: Callable[[str], None] | None = None,
        after: Callable[[], None] | None = None,
    ) -> dict[str, Any]:
        print(f"\n======== {number}. {label} ========")
        self.fresh()
        for sql in setup:
            self.run("setup", sql)
        self.conn.autocommit = False
        self.run("marker row", f"INSERT INTO {self.q(H)} (CASE_NO) VALUES ({number})")
        outcomes = []
        for sql in statements:
            if before_each:
                before_each(sql)
            result = self.run(label, sql)
            outcomes.append(
                {"sql": sql, "ok": result["ok"], "sqlstate": result.get("sqlstate", "")}
                | ({} if result["ok"] else {"message": result.get("message", "")[:160]})
            )
        rollback = "ok"
        try:
            self.conn.rollback()
        except Exception as exc:  # recorded, the probe goes on
            rollback = f"error {exc!s:.120}"
        self.conn.autocommit = True
        if after:
            after()
        committed = self.scalar(f"SELECT COUNT(*) FROM {self.q(H)} WHERE CASE_NO = ?", (number,))
        usable = self.scalar("SELECT 1 FROM SYSIBM.SYSDUMMY1")
        record = {
            "statements": outcomes,
            "rollback": rollback,
            "marker row kept (implicit commit)": committed,
            "connection usable": usable == 1,
            "after rollback": check(),
        }
        print(f"  {record}")
        return record


def checks(conn, library: str) -> None:
    schema = run_query(conn, "CURRENT SCHEMA", "SELECT CURRENT SCHEMA AS S FROM SYSIBM.SYSDUMMY1")
    print_query(schema)
    if not schema["ok"] or [row.get("S") for row in schema["rows"]] != [library]:
        raise ProbeError("check", "CURRENT SCHEMA is not the default library; nothing was changed")
    journal = run_query(
        conn,
        f"{library}: QSQJRN journal",
        "SELECT OBJNAME FROM TABLE(QSYS2.OBJECT_STATISTICS(?, '*JRN', 'QSQJRN')) X",
        (library,),
    )
    existing = run_query(
        conn, f"{library}: probe objects that exist already", PROBE_OBJECTS, (library,)
    )
    for result in (journal, existing):
        print_query(result)
    if not journal["ok"] or not existing["ok"]:
        raise ProbeError("check", "pre-checks could not run; nothing was changed")
    if not journal["rows"]:
        raise ProbeError("check", f"{library} has no QSQJRN journal; nothing was changed")
    if existing["rows"]:
        raise ProbeError("check", f"DJ11A objects exist in {library}; nothing was changed")
    if table_registry.list_path() is None:
        raise ProbeError(
            "check",
            f"{table_registry.ENV} is not set (run through scripts/pub400.sh); nothing was changed",
        )
    cursor = conn.cursor()
    try:
        reply = inquiry.read_reply(cursor)
    finally:
        cursor.close()
    print(f"\ninquiry message reply: {reply}")
    if reply != "*RQD":
        raise ProbeError(
            "check", f"the inquiry message reply is {reply}, not *RQD; nothing was changed"
        )


def run(conn, library: str) -> dict[str, Any]:
    p = Probe(conn, library)
    q = p.q
    cases: dict[str, Any] = {}
    try:
        print("\n======== setup ========")
        for name, body in ((H, "CASE_NO INTEGER"), (P, "ID INTEGER NOT NULL PRIMARY KEY")):
            if not p.create(name, body)["ok"]:
                raise ProbeError("refused", f"create {name} failed")
        p.run("parent row", f"INSERT INTO {q(P)} (ID) VALUES (1)")

        def drop_t_first() -> list[str]:
            return [f"DROP TABLE {q(T)}"]

        n = 0

        def add(label, statements, check, **kwargs):
            nonlocal n
            n += 1
            cases[label] = p.case(n, label, statements, check, **kwargs)

        add(
            "CREATE TABLE",
            [f"CREATE TABLE {q(T)} ({T_BODY})"],
            lambda: {"table exists": p.exists(T)},
            setup=drop_t_first(),
            before_each=lambda sql: table_registry.record(
                p.registry, table_registry.parse(sql, library)
            ),
        )
        add("DROP TABLE", [f"DROP TABLE {q(T)}"], lambda: {"table exists": p.exists(T)})
        add(
            "ADD COLUMN",
            [f"ALTER TABLE {q(T)} ADD COLUMN Z INTEGER"],
            lambda: {"column Z": p.column("Z", "DATA_TYPE")},
        )
        add(
            "DROP COLUMN",
            [f"ALTER TABLE {q(T)} DROP COLUMN N"],
            lambda: {"column N": p.column("N", "DATA_TYPE")},
        )
        add(
            "SET DATA TYPE (widening)",
            [f"ALTER TABLE {q(T)} ALTER COLUMN A SET DATA TYPE BIGINT"],
            lambda: {"A type": p.column("A", "DATA_TYPE")},
        )
        add(
            "DROP NOT NULL",
            [f"ALTER TABLE {q(T)} ALTER COLUMN A DROP NOT NULL"],
            lambda: {"A nullable": p.column("A", "IS_NULLABLE")},
        )
        add(
            "SET DEFAULT",
            [f"ALTER TABLE {q(T)} ALTER COLUMN A SET DEFAULT 7"],
            lambda: {"A default": p.column("A", "COLUMN_DEFAULT")},
        )
        add(
            "DROP DEFAULT",
            [f"ALTER TABLE {q(T)} ALTER COLUMN A DROP DEFAULT"],
            lambda: {"A default": p.column("A", "COLUMN_DEFAULT")},
        )
        add(
            "DROP IDENTITY",
            [f"ALTER TABLE {q(T)} ALTER COLUMN ID DROP IDENTITY"],
            lambda: {"ID identity": p.column("ID", "IS_IDENTITY")},
        )
        add(
            "SET DATA TYPE ... AS IDENTITY and the compound restart",
            [
                f"ALTER TABLE {q(T)} ALTER COLUMN ID SET DATA TYPE INTEGER "
                "GENERATED BY DEFAULT AS IDENTITY",
                "BEGIN DECLARE NEXT_ID BIGINT; "
                f"SET NEXT_ID = (SELECT COALESCE(MAX(ID), 0) + 1 FROM {q(T)}); "
                f"EXECUTE IMMEDIATE 'ALTER TABLE {q(T)} ALTER COLUMN ID RESTART WITH ' "
                "CONCAT VARCHAR(NEXT_ID); END",
            ],
            lambda: {"ID identity": p.column("ID", "IS_IDENTITY")},
            setup=[f"ALTER TABLE {q(T)} ALTER COLUMN ID DROP IDENTITY"],
        )
        add(
            "CREATE INDEX",
            [f"CREATE INDEX {q('DJ11AI')} ON {q(T)} (A)"],
            lambda: {"index DJ11AI": p.index_exists("DJ11AI")},
        )
        add(
            "CREATE UNIQUE INDEX",
            [f"CREATE UNIQUE INDEX {q('DJ11AU')} ON {q(T)} (V)"],
            lambda: {"index DJ11AU": p.index_exists("DJ11AU")},
        )
        add(
            "DROP INDEX",
            [f"DROP INDEX {q('DJ11AJ')}"],
            lambda: {"index DJ11AJ": p.index_exists("DJ11AJ")},
            setup=[f"CREATE INDEX {q('DJ11AJ')} ON {q(T)} (A)"],
        )
        add(
            "RENAME INDEX",
            [f"RENAME INDEX {q('DJ11AJ')} TO DJ11AI"],
            lambda: {
                "index DJ11AJ": p.index_exists("DJ11AJ"),
                "index DJ11AI": p.index_exists("DJ11AI"),
            },
            setup=[f"CREATE INDEX {q('DJ11AJ')} ON {q(T)} (A)"],
        )

        def rename_pending(sql: str) -> None:
            table_registry.rename_pending(p.registry, library, T, R)

        def rename_settle() -> None:
            # The list follows whatever the rollback left.
            if p.exists(R):
                table_registry.rename_done(p.registry, library, R)
            else:
                table_registry.rename_failed(p.registry, library, T, R)

        add(
            "RENAME TABLE",
            [f"RENAME TABLE {q(T)} TO {R}"],
            lambda: {"DJ11AT exists": p.exists(T), "DJ11AR exists": p.exists(R)},
            before_each=rename_pending,
            after=rename_settle,
        )
        add(
            "ADD CONSTRAINT UNIQUE",
            [f"ALTER TABLE {q(T)} ADD CONSTRAINT DJ11A_UQ UNIQUE (V)"],
            lambda: {"DJ11A_UQ": p.constraint_exists("DJ11A_UQ")},
        )
        add(
            "ADD CONSTRAINT CHECK",
            [f"ALTER TABLE {q(T)} ADD CONSTRAINT DJ11A_CK CHECK (A >= 0)"],
            lambda: {"DJ11A_CK": p.constraint_exists("DJ11A_CK")},
        )
        add(
            "ADD CONSTRAINT FOREIGN KEY",
            [f"ALTER TABLE {q(T)} ADD CONSTRAINT DJ11A_FK FOREIGN KEY (N) REFERENCES {q(P)} (ID)"],
            lambda: {"DJ11A_FK": p.constraint_exists("DJ11A_FK")},
        )
        add(
            "DROP CONSTRAINT",
            [f"ALTER TABLE {q(T)} DROP CONSTRAINT DJ11A_CK"],
            lambda: {"DJ11A_CK": p.constraint_exists("DJ11A_CK")},
            setup=[f"ALTER TABLE {q(T)} ADD CONSTRAINT DJ11A_CK CHECK (A >= 0)"],
        )
        add(
            "LABEL ON COLUMN",
            [f"LABEL ON COLUMN {q(T)}.A IS 'probe label'"],
            lambda: {"A label": p.column("A", "COLUMN_TEXT")},
        )
        add(
            "COMMENT ON TABLE",
            [f"COMMENT ON TABLE {q(T)} IS 'probe comment'"],
            lambda: {
                "comment": p.scalar(
                    "SELECT LONG_COMMENT FROM QSYS2.SYSTABLES "
                    "WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ?",
                    (library, T),
                )
            },
        )
        add(
            "a migration cancelled by CPA32B2 halfway",
            [
                f"CREATE TABLE {q(T)} ({T_BODY})",
                f"ALTER TABLE {q(T)} ADD COLUMN Z INTEGER",
                f"CREATE INDEX {q('DJ11AI')} ON {q(T)} (Z)",
                f"ALTER TABLE {q(T)} ALTER COLUMN V SET DATA TYPE NVARCHAR(5)",
            ],
            lambda: {"table exists": p.exists(T), "index DJ11AI": p.index_exists("DJ11AI")},
            setup=drop_t_first(),
            before_each=lambda sql: (
                table_registry.record(p.registry, table_registry.parse(sql, library))
                if sql.startswith("CREATE TABLE")
                else None
            ),
        )
        add(
            "UPDATE ... IS NULL, then SET NOT NULL cancelled by CPA32B2",
            [
                f"UPDATE {q(T)} SET N = -1 WHERE N IS NULL",
                f"ALTER TABLE {q(T)} ALTER COLUMN N SET NOT NULL",
            ],
            lambda: {
                "rows with N NULL": p.scalar(f"SELECT COUNT(*) FROM {q(T)} WHERE N IS NULL"),
                "N nullable": p.column("N", "IS_NULLABLE"),
            },
        )
    finally:
        with contextlib.suppress(Exception):  # cleanup goes on
            conn.rollback()
        conn.autocommit = True
        for name in TABLES:
            if p.exists(name):
                p.run(f"drop {name}", f"DROP TABLE {q(name)}")
        left = run_query(conn, "probe objects left", PROBE_OBJECTS, (library,))
        print_query(left)
        if not left["ok"] or left["rows"]:
            print(f"\nWARNING: DJ11A objects may be left in {library}: {left}", file=sys.stderr)
    print("\nSummary")
    for label, record in cases.items():
        print(
            f"  {label[:58]:<58} undone: {record['after rollback']}  "
            f"implicit commit: {record['marker row kept (implicit commit)']}"
        )
    return {"cases": cases, "left": left.get("rows"), "steps": p.steps}


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--execute", action="store_true", help="create, change and drop the tables")
    args = parser.parse_args(argv)
    conn = None
    try:
        settings = Settings.from_env(need_credentials=True)
        library = settings.default_library
        if not library:
            raise ProbeError("config", "DB2I_DEFAULT_LIBRARY is not set", 1)
        # DBQ as the backend sets it: the library becomes CURRENT SCHEMA, so the
        # constraint names land next to their table.
        conn = connect(
            settings, {"CMT": "1", "TRUEAUTOCOMMIT": "1", "DBQ": library}, autocommit=True
        )
        checks(conn, library)
        if not args.execute:
            print("\nDry run: nothing was changed. Re-run with --execute to apply.")
            return 0
        result = run(conn, library)
        print(f"\nresult saved to {write_result('lib_rollback_ddl', result, settings)}")
    except ProbeError as exc:
        print(f"\nPROBE FAILED [{exc.category}]: {exc}", file=sys.stderr)
        return exc.exit_code
    finally:
        if conn is not None:
            conn.close()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
