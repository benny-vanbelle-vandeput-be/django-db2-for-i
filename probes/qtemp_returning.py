"""Returning columns from INSERT and UPDATE, DEFAULT in VALUES, an explicit 0
in an identity column (phase 5, step 0).

Writes only to QTEMP (tables that disappear with the job); reads nothing
outside it. Without commitment control (CMT=0): QTEMP tables have no journal.
Each statement's outcome is recorded with its SQLSTATE and SQLCODE.

- ``can_return_columns_from_insert``: ``SELECT ... FROM FINAL TABLE (INSERT
  ...)`` for one row, with the identity and a column default returned.
- ``can_return_rows_from_bulk_insert``: the same for several rows, with and
  without ``ORDER BY INPUT SEQUENCE``, rows sent in an order the identity
  does not follow (an explicit key first, generated keys after).
- ``can_return_rows_from_update``: ``FINAL TABLE (UPDATE ...)``.
- ``supports_default_keyword_in_insert`` / ``..._in_bulk_insert``: ``DEFAULT``
  in ``VALUES``, one row and several rows, also inside ``FINAL TABLE``.
- ``allows_auto_pk_0``: an explicit 0 in a ``GENERATED BY DEFAULT AS
  IDENTITY`` column.
- What ``cursor.rowcount`` reports for each form.

Usage (inside the "tests" container):
    nox -s probe -- returning

Findings go to docs/IBMI_NOTES.md.
"""

from __future__ import annotations

from typing import Any

from _common import Settings
from qtemp_alter_table import _execute
from qtemp_later_flags import _execute_error, _query, _step, connection_attributes  # noqa: F401

NEEDS_CONNECTION = True
AUTOCOMMIT = True

TABLE = "QTEMP.PRET"
CREATE = (
    f"CREATE TABLE {TABLE} (ID INTEGER GENERATED BY DEFAULT AS IDENTITY, "
    "NAME NVARCHAR(20), D INTEGER DEFAULT 7)"
)
NAMES = ["delta", "alpha", "charlie", "bravo", "echo"]


def _rowcount(conn, sql: str, params=()) -> dict[str, Any]:
    """Execute a statement and report the driver's rowcount (and rows, if any)."""
    import pyodbc

    cursor = conn.cursor()
    try:
        cursor.execute(sql, params)
        rows = cursor.fetchall() if cursor.description else None
        outcome: dict[str, Any] = {"result": "ok", "rowcount": cursor.rowcount}
        if rows is not None:
            outcome["rows"] = [[repr(value) for value in row] for row in rows]
        return outcome
    except pyodbc.Error as exc:
        return {"result": "error", **_execute_error(exc)}
    finally:
        cursor.close()


def _fresh(conn, results, key: str) -> bool:
    _execute(conn, f"DROP TABLE {TABLE}")
    return _step(results, key, _execute(conn, CREATE))["result"] == "ok"


def _single(conn, results) -> None:
    if not _fresh(conn, results, "create"):
        return
    _step(
        results,
        "plain insert: rowcount",
        _rowcount(conn, f"INSERT INTO {TABLE} (NAME) VALUES (?)", ["plain"]),
    )
    _step(
        results,
        "final table, one row: ID, D",
        _rowcount(
            conn, f"SELECT ID, D FROM FINAL TABLE (INSERT INTO {TABLE} (NAME) VALUES (?))", ["one"]
        ),
    )
    _step(
        results,
        "final table, one row, explicit key 100",
        _rowcount(
            conn,
            f"SELECT ID FROM FINAL TABLE (INSERT INTO {TABLE} (ID, NAME) VALUES (?, ?))",
            [100, "explicit"],
        ),
    )
    _step(
        results,
        "final table, one row: column names quoted",
        _rowcount(
            conn,
            f'SELECT "ID", "D" FROM FINAL TABLE (INSERT INTO {TABLE} ("NAME") VALUES (?))',
            ["quoted"],
        ),
    )
    _step(
        results,
        "IDENTITY_VAL_LOCAL() after final table insert",
        _query(conn, "SELECT IDENTITY_VAL_LOCAL() FROM SYSIBM.SYSDUMMY1"),
    )


def _multi(conn, results) -> None:
    if not _fresh(conn, results, "multi: create"):
        return
    values = ", ".join(["(?)"] * len(NAMES))
    _step(
        results,
        "final table, 5 rows, no ORDER BY",
        _rowcount(
            conn,
            f"SELECT ID, NAME FROM FINAL TABLE (INSERT INTO {TABLE} (NAME) VALUES {values})",
            NAMES,
        ),
    )
    _step(
        results,
        "final table, 5 rows, ORDER BY INPUT SEQUENCE",
        _rowcount(
            conn,
            f"SELECT ID, NAME FROM FINAL TABLE (INSERT INTO {TABLE} (NAME) VALUES {values}) "
            "ORDER BY INPUT SEQUENCE",
            NAMES,
        ),
    )
    # An explicit key in the middle: the input order is not the key order.
    _step(
        results,
        "final table, 3 rows with an explicit key 500 in the middle, ORDER BY INPUT SEQUENCE",
        _rowcount(
            conn,
            f"SELECT ID, NAME FROM FINAL TABLE (INSERT INTO {TABLE} (ID, NAME) "
            "VALUES (DEFAULT, ?), (500, ?), (DEFAULT, ?)) ORDER BY INPUT SEQUENCE",
            ["first", "second", "third"],
        ),
    )
    many = [f"n{i:03d}" for i in range(200, 0, -1)]
    _step(
        results,
        "final table, 200 rows in reverse name order, ORDER BY INPUT SEQUENCE: names",
        _summary(
            _rowcount(
                conn,
                f"SELECT NAME FROM FINAL TABLE (INSERT INTO {TABLE} (NAME) VALUES "
                f"{', '.join(['(?)'] * len(many))}) ORDER BY INPUT SEQUENCE",
                many,
            ),
            [repr(name) for name in many],
        ),
    )
    _step(
        results,
        "multi-row plain insert: rowcount",
        _rowcount(conn, f"INSERT INTO {TABLE} (NAME) VALUES (?), (?), (?)", ["x", "y", "z"]),
    )


def _summary(outcome: dict[str, Any], expected: list[str]) -> dict[str, Any]:
    """A long result as a comparison with the sent order instead of every row."""
    if outcome["result"] != "ok":
        return outcome
    names = [row[0] for row in outcome.pop("rows")]
    return {**outcome, "rows": len(names), "in_input_order": names == expected}


def _defaults(conn, results) -> None:
    if not _fresh(conn, results, "default: create"):
        return
    _step(
        results,
        "DEFAULT in VALUES, one row",
        _rowcount(conn, f"INSERT INTO {TABLE} (ID, NAME, D) VALUES (DEFAULT, ?, DEFAULT)", ["d1"]),
    )
    _step(
        results,
        "DEFAULT in VALUES, several rows, mixed with values",
        _rowcount(
            conn,
            f"INSERT INTO {TABLE} (ID, NAME, D) VALUES (DEFAULT, ?, DEFAULT), (DEFAULT, ?, ?)",
            ["d2", "d3", 9],
        ),
    )
    _step(
        results,
        "DEFAULT in VALUES inside final table",
        _rowcount(
            conn,
            f"SELECT ID, NAME, D FROM FINAL TABLE (INSERT INTO {TABLE} (ID, NAME, D) "
            "VALUES (DEFAULT, ?, DEFAULT), (DEFAULT, ?, ?)) ORDER BY INPUT SEQUENCE",
            ["d4", "d5", 11],
        ),
    )
    _step(
        results,
        "every column DEFAULT (INSERT ... VALUES (DEFAULT, DEFAULT, DEFAULT))",
        _rowcount(conn, f"INSERT INTO {TABLE} VALUES (DEFAULT, DEFAULT, DEFAULT)"),
    )
    _step(
        results,
        "INSERT ... DEFAULT VALUES",
        _rowcount(conn, f"INSERT INTO {TABLE} DEFAULT VALUES"),
    )
    _step(results, "default: read", _query(conn, f"SELECT ID, NAME, D FROM {TABLE} ORDER BY ID"))


def _auto_pk_0(conn, results) -> None:
    if not _fresh(conn, results, "pk 0: create"):
        return
    _step(
        results,
        "explicit 0 in the identity column",
        _rowcount(conn, f"INSERT INTO {TABLE} (ID, NAME) VALUES (?, ?)", [0, "zero"]),
    )
    _step(
        results,
        "generated key after an explicit 0",
        _rowcount(
            conn, f"SELECT ID FROM FINAL TABLE (INSERT INTO {TABLE} (NAME) VALUES (?))", ["next"]
        ),
    )
    _step(results, "pk 0: read", _query(conn, f"SELECT ID, NAME FROM {TABLE} ORDER BY ID"))


def _update(conn, results) -> None:
    if not _fresh(conn, results, "update: create"):
        return
    _execute(conn, f"INSERT INTO {TABLE} (NAME) VALUES ('u1'), ('u2'), ('u3')")
    _step(
        results,
        "final table (UPDATE ...)",
        _rowcount(
            conn,
            f"SELECT ID, NAME FROM FINAL TABLE (UPDATE {TABLE} SET NAME = ? WHERE ID <= 2)",
            ["changed"],
        ),
    )
    _step(
        results,
        "old table (UPDATE ...)",
        _rowcount(conn, f"SELECT ID, NAME FROM OLD TABLE (UPDATE {TABLE} SET D = 8)"),
    )
    _step(
        results,
        "old table (DELETE ...)",
        _rowcount(conn, f"SELECT ID FROM OLD TABLE (DELETE FROM {TABLE} WHERE ID = 3)"),
    )


def run(settings: Settings, conn) -> dict[str, Any]:
    results: dict[str, Any] = {"scope": "QTEMP only (tables gone with the job)"}
    for part in (_single, _multi, _defaults, _auto_pk_0, _update):
        print(f" -- {part.__name__.strip('_')}")
        part(conn, results)
    _execute(conn, f"DROP TABLE {TABLE}")
    return results
