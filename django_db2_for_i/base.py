"""DatabaseWrapper: connection lifecycle and wiring of the backend classes.

Settings::

    DATABASES = {
        "default": {
            "ENGINE": "django_db2_for_i",
            "NAME": "DJTEST",          # default schema (library)
            "HOST": "ibmi.example.com",
            "USER": "...",
            "PASSWORD": "...",
            "OPTIONS": {
                "ssl": True,                 # TLS (port 9471); False: port 8471
                "isolation_level": "*CS",    # *NONE, *CHG, *CS, *ALL, *RR or SQL names
                "login_timeout": 10,         # seconds
                "driver": "pyodbc",
                "driver_attributes": {},     # extra driver keywords, e.g. {"XDYNAMIC": "1"}
                "capabilities": None,        # profile name and/or overrides
            },
        }
    }

``PORT`` is not supported: the driver connects to the database host server
port (8471, or 9471 with TLS).
"""

