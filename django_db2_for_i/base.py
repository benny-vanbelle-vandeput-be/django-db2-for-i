    def __init__(self, *args: Any, **kwargs: Any):
        super().__init__(*args, **kwargs)
        self._capabilities: caps.ServerCapabilities | None = None
        # INQMSGRPY read before the backend changed it on this connection's
        # job (None: unchanged); restored at close.
        self._inquiry_reply_original: str | None = None
        self._inquiry_reply_active: str | None = None

    # --- Configuration ---------------------------------------------------------

    @cached_property
    def options(self) -> Mapping[str, Any]:
        options = self.settings_dict["OPTIONS"]
        unknown = set(options) - OPTION_NAMES
        if unknown:
            raise ImproperlyConfigured(
                f"Unknown OPTIONS for database '{self.alias}': {', '.join(sorted(unknown))}. "
                f"Known: {', '.join(sorted(OPTION_NAMES))}."
            )
        return options

    @cached_property
    def capability_config(self) -> caps.CapabilityConfig:
        try:
            return caps.CapabilityConfig.from_option(self.options.get("capabilities"))
        except caps.CapabilityError as exc:
            raise ImproperlyConfigured(f"OPTIONS['capabilities']: {exc}") from None

    @property
    def capabilities(self) -> caps.ServerCapabilities:
        """What the server can do; connects only if detection is needed."""
        if self._capabilities is None:
            if self.capability_config.needs_detection:
                self.ensure_connection()  # detection runs in init_connection_state()
            else:
                self._capabilities = self._checked(self.capability_config.build())
        return self._capabilities

    @staticmethod
    def _checked(capabilities: caps.ServerCapabilities) -> caps.ServerCapabilities:
        """Refuse capabilities the backend cannot work without (yet)."""
        if not capabilities.has_boolean_type:
            raise NotSupportedError(
                "BooleanField needs the BOOLEAN data type (has_boolean_type); "
                "the SMALLINT fallback is not implemented."
            )
        return capabilities

    @cached_property
    def inquiry_message_reply(self) -> str | None:
        """OPTIONS['inquiry_message_reply'], validated; None when not set."""
        value = self.options.get(inquiry.OPTION)
        if value is None:
            return None
        try:
            return inquiry.normalize_reply(value)
        except ValueError as exc:
            raise ImproperlyConfigured(f"OPTIONS['{inquiry.OPTION}']: {exc}") from None

    @cached_property
    def driver(self) -> Database.Driver:
        try:
            return get_driver(self.options.get("driver", "pyodbc"))
        except ValueError as exc:
            raise ImproperlyConfigured(f"OPTIONS['driver']: {exc}") from None

    # --- Connection --------------------------------------------------------------

    def get_connection_params(self) -> dict[str, Any]:
        settings_dict = self.settings_dict
        options = self.options
        if not settings_dict["HOST"]:
            raise ImproperlyConfigured(f"Database '{self.alias}': HOST is required.")
        if settings_dict["PORT"]:
            raise ImproperlyConfigured(
                f"Database '{self.alias}': PORT is not supported; the driver uses the "
                "database host server port (8471, or 9471 with OPTIONS['ssl'])."
            )
        name = settings_dict["NAME"]
        if not name and self.alias != NO_DB_ALIAS:
            raise ImproperlyConfigured(
                f"Database '{self.alias}': NAME (the default schema / library) is required."
            )
        try:
            Database.normalize_isolation_level(options.get("isolation_level", "*CS"))
        except ValueError as exc:
            raise ImproperlyConfigured(f"OPTIONS['isolation_level']: {exc}") from None
        _ = self.inquiry_message_reply  # validate before connecting
        params = Database.ConnectionParams(
            host=settings_dict["HOST"],
            user=settings_dict["USER"],
            password=settings_dict["PASSWORD"],
            default_schema=name.upper() if name else None,
            ssl=bool(options.get("ssl", True)),
            isolation_level=options.get("isolation_level", "*CS"),
            login_timeout=int(options.get("login_timeout", Database.DEFAULT_LOGIN_TIMEOUT)),
            attributes=dict(options.get("driver_attributes", {})),
        )
        return {"params": params}

    def get_new_connection(self, conn_params: dict[str, Any]) -> Database.Connection:
        # A new connection is a new job: nothing to restore from the old one.
        self._inquiry_reply_original = self._inquiry_reply_active = None
        try:
            return self.driver.connect(
                conn_params["params"], autocommit=self.settings_dict["AUTOCOMMIT"]
            )
        except ValueError as exc:
            # Invalid connection parameters (never contains the password).
            raise ImproperlyConfigured(f"Database '{self.alias}': {exc}") from None

    def init_connection_state(self) -> None:
        if self._capabilities is None:
            config = self.capability_config
            try:
                if config.needs_detection:
                    detected = caps.detect(
                        self.connection.server_version(),
                        self._run_probe,
                        config.overrides,
                        cache_key=self.settings_dict["HOST"],
                    )
                else:
                    detected = config.build()
            except caps.CapabilityError as exc:
                raise NotSupportedError(str(exc)) from None
            self._capabilities = self._checked(detected)
        super().init_connection_state()
        if self.inquiry_message_reply is not None:
            self._change_inquiry_reply(self.inquiry_message_reply)

    # --- Inquiry message reply (inquiry.py) --------------------------------------

    def set_inquiry_message_reply(self, value: str) -> None:
        """Set the job's INQMSGRPY (*RQD, *DFT, *SYSRPYL) for this connection.

        The value the job had before is read first and restored by
        ``restore_inquiry_message_reply()`` or when the connection closes.
        If it cannot be read, nothing is changed and DatabaseError is raised.
        """
        reply = inquiry.normalize_reply(value)
        self.ensure_connection()
        self._change_inquiry_reply(reply)

    def restore_inquiry_message_reply(self) -> bool:
        """Restore the INQMSGRPY read before the first change; False if unchanged."""
        original = self._inquiry_reply_original
        if original is None or self.connection is None:
            return False
        with self.wrap_database_errors, self.connection.cursor() as cursor:
            cursor.execute(inquiry.change_sql(original))
        self._inquiry_reply_original = self._inquiry_reply_active = None
        return True

    def _change_inquiry_reply(self, reply: str) -> None:
        with self.wrap_database_errors, self.connection.cursor() as cursor:
            if self._inquiry_reply_original is None:
                try:
                    original = inquiry.read_reply(cursor)
                except (inquiry.InquiryReplyError, Database.Error) as exc:
                    raise DatabaseError(
                        f"Database '{self.alias}': the job's current inquiry message reply "
                        f"could not be read ({exc}), so it is not changed to {reply}: it "
                        "could not be restored when the connection closes."
                    ) from None
                self._inquiry_reply_original = original
            cursor.execute(inquiry.change_sql(reply))
        self._inquiry_reply_active = reply
        logger.debug(
            "Inquiry message reply of database '%s' set to %s (restores %s at close).",
            self.alias,
            reply,
            self._inquiry_reply_original,
        )

    def _close(self):
        if self.connection is not None and self._inquiry_reply_original is not None:
            try:
                self.restore_inquiry_message_reply()
            except Exception as exc:  # closing must not fail because of this
                logger.warning(
                    "Database '%s': could not restore the job's inquiry message reply %s "
                    "before closing: %s",
                    self.alias,
                    self._inquiry_reply_original,
                    exc,
                )
            self._inquiry_reply_original = self._inquiry_reply_active = None
        return super()._close()

    def _run_probe(self, sql: str) -> bool:
        """Targeted capability probe: True if the statement succeeds."""
        try:
            with self.connection.cursor() as cursor:
                cursor.execute(sql)
                if cursor.description:
                    cursor.fetchall()
        except Database.Error:
            return False
        return True

    def get_database_version(self) -> tuple[int, int]:
        return self.capabilities.release

    def create_cursor(self, name: str | None = None) -> FormatStyleCursor:
        return FormatStyleCursor(self.connection.cursor())

    def _set_autocommit(self, autocommit: bool) -> None:
        with self.wrap_database_errors:
            self.connection.autocommit = autocommit

    def _nodb_cursor(self):
        # Django opens this extra connection for CREATE/DROP DATABASE. This
        # backend never does: test databases are existing libraries
        # (TEST['CREATE_DB'] = False), and shared systems limit connections.
        raise NotSupportedError(
            "Db2 for i backend: no connection without a database is opened; use "
            "TEST['CREATE_DB'] = False with an existing library for tests."
        )

    def is_usable(self) -> bool:
        # The driver knows when the connection cannot run statements any more
        # (drivers/pyodbc.py: SQL0443 on a parameterized service, SQL0519).
        if not self.connection.usable:
            return False
        try:
            with self.connection.cursor() as cursor:
                cursor.execute("SELECT 1 FROM SYSIBM.SYSDUMMY1")
                cursor.fetchall()
        except Database.Error:
            return False
        return True
