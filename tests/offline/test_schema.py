def _create_sql(**fields) -> str:
    model = type(
        "DefaultProbe",
        (models.Model,),
        {"__module__": __name__, "Meta": type("Meta", (), {"app_label": "testapp"}), **fields},
    )
    try:
        with connection.schema_editor(collect_sql=True, atomic=False) as editor:
            editor.create_model(model)
        return editor.collected_sql[0]
    finally:
        apps.all_models["testapp"].pop("defaultprobe", None)
        apps.clear_cache()


def test_db_default_is_a_bare_constant_without_cast() -> None:
    sql = _create_sql(n=models.IntegerField(primary_key=True, db_default=1))
    assert '"N" INTEGER DEFAULT 1 NOT NULL PRIMARY KEY' in sql
    assert "CAST" not in sql


def test_db_default_none_writes_no_default() -> None:
    sql = _create_sql(n=models.IntegerField(null=True, db_default=None))
    assert sql.endswith('"N" INTEGER);')


def test_db_default_expression_is_not_supported() -> None:
    with pytest.raises(NotSupportedError, match="only constants"):
        _create_sql(n=models.DateTimeField(db_default=Now()))


def test_create_table_follows_local_fields_with_inherited_fields() -> None:
    """Issue #23: the columns of CREATE TABLE are _meta.local_fields, in order.

    Fields from an abstract mixin and an abstract base keep their
    creation_counter, so they come before the model's own fields, in the
    order they were defined, not in the order of the bases.
    """
    import re

    (create,) = collect(("create_model", Article))
    body = create.split("(", 1)[1]
    columns = re.findall(r'(?:^|, )"([A-Z0-9_]+)" ', body)
    expected = [field.column.upper() for field in Article._meta.local_fields]
    assert columns == expected
    assert expected == ["ID", "CREATED", "TITLE", "SUBTITLE", "BODY", "RANK"]


def test_rename_column_is_not_supported() -> None:
    """IBM i 7.5 and 7.6 have no statement to rename a column (probe qtemp_renames)."""
    old = Author._meta.get_field("name")
    new = models.CharField(max_length=100)
    new.set_attributes_from_name("full_name")
    with (
        pytest.raises(NotSupportedError, match="db_column='name'") as info,
        connection.schema_editor(collect_sql=True, atomic=False) as editor,
    ):
        editor.alter_field(Author, old, new, strict=True)
    assert 'See "Renaming a column" in docs/user/Known-Limitations.md.' in str(info.value)
    assert connection.connection is None, "collecting SQL must not connect"


def test_rename_field_with_db_column_writes_nothing() -> None:
    """The workaround: the renamed field keeps the column (db_column), no SQL."""
    old = Author._meta.get_field("name")
    new = models.CharField(max_length=100, db_column="name")
    new.set_attributes_from_name("full_name")
    with connection.schema_editor(collect_sql=True, atomic=False) as editor:
        editor.alter_field(Author, old, new, strict=True)
    assert editor.collected_sql == []


@pytest.mark.parametrize(
    ("old", "new"),
    [
        (models.TextField(), models.DateField()),
        (models.CharField(max_length=10), models.IntegerField()),
        (models.IntegerField(), models.BooleanField()),
        (models.DateField(), models.DateTimeField()),
        (models.BinaryField(), models.TextField()),
        (models.BinaryField(), models.CharField(max_length=10)),
    ],
    ids=["text-date", "char-int", "int-bool", "date-timestamp", "blob-nclob", "blob-nvarchar"],
)
def test_type_change_db2_cannot_make_is_refused_before_any_sql(old, new) -> None:
    """SQL0190 pairs (probe qtemp_type_changes): NotSupportedError, no SQL at all."""
    for field in (old, new):
        field.set_attributes_from_name("info")
        field.model = Author
    with (
        pytest.raises(NotSupportedError, match=r"in place \(SQL0190\)\. Add a new field") as info,
        connection.schema_editor(collect_sql=True, atomic=False) as editor,
    ):
        editor.alter_field(Author, old, new, strict=True)
    assert editor.collected_sql == []
    assert '"Changing a column to an incompatible type"' in str(info.value)


