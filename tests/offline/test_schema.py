"""DDL collected with schema_editor(collect_sql=True) (no server needed).

atomic=False everywhere: with can_rollback_ddl an atomic schema editor enters
transaction.atomic(), which opens a connection even when it only collects SQL.
The collected SQL is the same.
"""

import datetime as dt
from decimal import Decimal

import pytest
from django.apps import apps
from django.db import NotSupportedError, connection, models
from django.db.models.functions import Now

from tests.testapp.models import Article, Author, Book, Node, Tag


def collect(*actions) -> list[str]:
    with connection.schema_editor(collect_sql=True, atomic=False) as editor:
        for action, model in actions:
            getattr(editor, action)(model)
    assert connection.connection is None, "collecting SQL must not connect"
    return editor.collected_sql


def test_create_author() -> None:
    assert collect(("create_model", Author)) == [
        'CREATE TABLE "TESTAPP_AUTHOR" ("ID" INTEGER GENERATED BY DEFAULT AS IDENTITY '
        'NOT NULL PRIMARY KEY, "NAME" NVARCHAR(100) NOT NULL);'
    ]


def test_create_book_types_and_indexes() -> None:
    assert collect(("create_model", Book)) == [
        'CREATE TABLE "TESTAPP_BOOK" ("ID" BIGINT GENERATED BY DEFAULT AS IDENTITY '
        'NOT NULL PRIMARY KEY, "AUTHOR_ID" INTEGER NOT NULL, "TITLE" NVARCHAR(200) NOT NULL, '
        '"PUBLISHED" TIMESTAMP(6), "READING_TIME" TIME, "AVAILABLE" BOOLEAN NOT NULL, '
        '"PAGES" INTEGER NOT NULL CHECK (pages >= 0));',
        'CREATE INDEX "TESTAPP_BOOK_AUTHOR_ID_B4B7B7BF" ON "TESTAPP_BOOK" ("AUTHOR_ID");',
        'CREATE INDEX "TESTAPP_BOOK_TITLE_C797B345" ON "TESTAPP_BOOK" ("TITLE");',
    ]


