"""DDL collected with schema_editor(collect_sql=True) (no server needed)."""

import datetime as dt
from decimal import Decimal

import pytest
from django.db import connection

from tests.testapp.models import Author, Book, Node, Tag


def collect(*actions) -> list[str]:
    with connection.schema_editor(collect_sql=True) as editor:
        for action, model in actions:
            getattr(editor, action)(model)
    assert connection.connection is None, "collecting SQL must not connect"
    return editor.collected_sql


def test_create_author() -> None:
    assert collect(("create_model", Author)) == [
        'CREATE TABLE "TESTAPP_AUTHOR" ("ID" INTEGER GENERATED BY DEFAULT AS IDENTITY '
        'NOT NULL PRIMARY KEY, "NAME" NVARCHAR(100) NOT NULL);'
    ]


def test_create_book_types_and_indexes() -> None:
    assert collect(("create_model", Book)) == [
        'CREATE TABLE "TESTAPP_BOOK" ("ID" BIGINT GENERATED BY DEFAULT AS IDENTITY '
        'NOT NULL PRIMARY KEY, "AUTHOR_ID" INTEGER NOT NULL, "TITLE" NVARCHAR(200) NOT NULL, '
        '"PUBLISHED" TIMESTAMP(6), "READING_TIME" TIME, "AVAILABLE" BOOLEAN NOT NULL, '
        '"PAGES" INTEGER NOT NULL CHECK (pages >= 0));',
        'CREATE INDEX "TESTAPP_BOOK_AUTHOR_ID_B4B7B7BF" ON "TESTAPP_BOOK" ("AUTHOR_ID");',
        'CREATE INDEX "TESTAPP_BOOK_TITLE_C797B345" ON "TESTAPP_BOOK" ("TITLE");',
    ]


def test_create_node_small_identity() -> None:
    assert collect(("create_model", Node)) == [
        'CREATE TABLE "TESTAPP_NODE" ("ID" SMALLINT GENERATED BY DEFAULT AS IDENTITY '
        'NOT NULL PRIMARY KEY, "PARENT_ID" SMALLINT);',
        'CREATE INDEX "TESTAPP_NODE_PARENT_ID_B90D5D31" ON "TESTAPP_NODE" ("PARENT_ID");',
    ]


def test_create_tag_uuid_and_unique() -> None:
    assert collect(("create_model", Tag)) == [
        'CREATE TABLE "TESTAPP_TAG" ("ID" CHAR(32) NOT NULL PRIMARY KEY, '
        '"LABEL" NVARCHAR(50) NOT NULL UNIQUE);'
    ]


def test_delete_model() -> None:
    assert collect(("delete_model", Author)) == ['DROP TABLE "TESTAPP_AUTHOR" CASCADE;']


def test_no_foreign_keys_while_disabled() -> None:
    sql = " ".join(collect(("create_model", Book), ("create_model", Node)))
    assert "FOREIGN KEY" not in sql


def test_foreign_keys_use_no_action(monkeypatch: pytest.MonkeyPatch) -> None:
    # When foreign keys are enabled they get no ON DELETE clause (Db2 default
    # NO ACTION), never RESTRICT.
    monkeypatch.setattr(connection.features, "supports_foreign_keys", True)
    sql = collect(("create_model", Node))
    assert sql[1] == (
        'ALTER TABLE "TESTAPP_NODE" ADD CONSTRAINT '
        '"TESTAPP_NODE_PARENT_ID_B90D5D31_FK_TESTAPP_NODE_ID" '
        'FOREIGN KEY ("PARENT_ID") REFERENCES "TESTAPP_NODE" ("ID");'
    )
    assert not any("RESTRICT" in statement or "ON DELETE" in statement for statement in sql)


# --- Literals --------------------------------------------------------------------


@pytest.mark.parametrize(
    ("value", "literal"),
    [
        (None, "NULL"),
        (True, "TRUE"),
        (False, "FALSE"),
        (42, "42"),
        (Decimal("1.50"), "1.50"),
        (1.5, "1.5"),
        ("it's", "'it''s'"),
        ("100%", "'100%'"),
        (dt.date(2026, 10, 17), "'2026-10-17'"),
        (dt.time(13, 45, 30), "'13:45:30'"),
        (dt.datetime(2026, 10, 17, 13, 45, 30, 123456), "'2026-10-17 13:45:30.123456'"),
        (b"\x01\xab", "BX'01AB'"),
    ],
)
def test_quote_value(value, literal: str) -> None:
    with connection.schema_editor(collect_sql=True) as editor:
        assert editor.quote_value(value) == literal


def test_quote_value_rejects_unknown_types() -> None:
    with (
        connection.schema_editor(collect_sql=True) as editor,
        pytest.raises(ValueError, match="Cannot quote"),
    ):
        editor.quote_value(object())


def test_prepare_default_escapes_percent() -> None:
    with connection.schema_editor(collect_sql=True) as editor:
        assert editor.prepare_default("100%") == "'100%%'"
