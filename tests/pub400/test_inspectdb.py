"""inspectdb on tables that were not created by Django (phase 4 step D; writes).

The real-world pattern: an existing IBM i application's tables, created with
plain SQL in the types such applications use (CHAR, NUMERIC, DECIMAL, CLOB, a
primary key that is no identity column), get models from ``manage.py
inspectdb``, and the application reads and writes them through those models
(``managed = False``).

The two tables are created in the marked test library (``testapp_tables``),
recorded on the cleanup list before their CREATE TABLE, and dropped again.
"""

import datetime as dt
import types
from decimal import Decimal
from io import StringIO

import pytest
from django.core.management import call_command
from django.db import models
from django.test.utils import isolate_apps

pytestmark = pytest.mark.usefixtures("testapp_tables")

CUSTOMER = "LEGACY_CUSTOMER"
ORDER = "LEGACY_ORDER"

CREATE_CUSTOMER = (
    f"CREATE TABLE {CUSTOMER} ("
    "CUSTNO NUMERIC(7, 0) NOT NULL PRIMARY KEY, "
    "NAME CHAR(30) NOT NULL, "
    "EMAIL VARCHAR(100), "
    "CITY NVARCHAR(40), "
    "CREDIT DECIMAL(9, 2) NOT NULL DEFAULT 0, "
    "ACTIVE BOOLEAN NOT NULL DEFAULT TRUE, "
    "SINCE DATE, "
    "NOTES CLOB(1M), "
    "CONSTRAINT LEGACY_CUSTOMER_EMAIL UNIQUE (EMAIL))"
)
CREATE_ORDER = (
    f"CREATE TABLE {ORDER} ("
    "ORDERNO INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "
    "CUSTNO NUMERIC(7, 0) NOT NULL, "
    "LINES SMALLINT NOT NULL, "
    "WEIGHT BIGINT, "
    "PICKED TIME, "
    "PLACED TIMESTAMP NOT NULL, "
    "CONSTRAINT LEGACY_ORDER_CUSTNO FOREIGN KEY (CUSTNO) REFERENCES "
    f"{CUSTOMER} (CUSTNO), "
    "CONSTRAINT LEGACY_ORDER_LINES CHECK (LINES > 0))"
)

# inspectdb's model names; introspection reports the tables in lowercase.
TABLES = {"LegacyCustomer": CUSTOMER.lower(), "LegacyOrder": ORDER.lower()}

# What inspectdb writes for each column: (field class, the options checked).
EXPECTED = {
    "LegacyCustomer": {
        "custno": (
            models.DecimalField,
            {"primary_key": True, "max_digits": 7, "decimal_places": 0},
        ),
        "name": (models.CharField, {"max_length": 30, "null": False}),
        "email": (models.CharField, {"max_length": 100, "null": True, "unique": True}),
        "city": (models.CharField, {"max_length": 40, "null": True}),
        "credit": (models.DecimalField, {"max_digits": 9, "decimal_places": 2, "null": False}),
        "active": (models.BooleanField, {"null": False}),
        "since": (models.DateField, {"null": True}),
        "notes": (models.TextField, {"null": True}),
    },
    "LegacyOrder": {
        "orderno": (models.AutoField, {"primary_key": True}),
        "custno": (models.ForeignKey, {"null": False}),
        "lines": (models.SmallIntegerField, {"null": False}),
        "weight": (models.BigIntegerField, {"null": True}),
        "picked": (models.TimeField, {"null": True}),
        "placed": (models.DateTimeField, {"null": False}),
    },
}


@pytest.fixture
def legacy_tables(live):
    with live.cursor() as cursor:
        cursor.execute(CREATE_CUSTOMER)
        try:
            cursor.execute(CREATE_ORDER)
            try:
                yield
            finally:
                cursor.execute(f"DROP TABLE {ORDER}")
        finally:
            cursor.execute(f"DROP TABLE {CUSTOMER}")


def inspect(*tables: str) -> str:
    out = StringIO()
    call_command("inspectdb", *(table.lower() for table in tables), stdout=out)
    return out.getvalue()


def load(code: str) -> types.SimpleNamespace:
    """The generated module's models, in an app registry of their own."""
    namespace = {"__name__": "tests.testapp.inspected"}
    exec(compile(code, "<inspectdb>", "exec"), namespace)  # our own output, from inspectdb
    return types.SimpleNamespace(**namespace)


def test_inspectdb_writes_the_expected_fields(live, legacy_tables) -> None:
    code = inspect(CUSTOMER, ORDER)
    assert "This field type is a guess" not in code, code
    with isolate_apps("tests.testapp"):
        module = load(code)
        for model_name, fields in EXPECTED.items():
            model = getattr(module, model_name)
            assert model._meta.managed is False
            assert model._meta.db_table == TABLES[model_name]
            for name, (field_class, options) in fields.items():
                field = model._meta.get_field(name)
                assert type(field) is field_class, (model_name, name, code)
                for option, value in options.items():
                    assert getattr(field, option) == value, (model_name, name, option, code)
        assert module.LegacyOrder._meta.get_field("custno").related_model is module.LegacyCustomer


def test_the_inspected_models_read_and_write_rows(live, legacy_tables) -> None:
    code = inspect(CUSTOMER, ORDER)
    with isolate_apps("tests.testapp"):
        module = load(code)
        customer = module.LegacyCustomer.objects.create(
            custno=Decimal(1001),
            name="Acme",
            email="sales@acme.example",
            city="Gent",
            credit=Decimal("1250.50"),
            active=True,
            since=dt.date(2001, 5, 17),
            notes="first customer",
        )
        placed = dt.datetime(2026, 10, 27, 9, 30, 15, 123456, tzinfo=dt.UTC)
        order = module.LegacyOrder.objects.create(
            custno=customer, lines=3, weight=2500, picked=dt.time(9, 45), placed=placed
        )
        assert order.orderno is not None
        row = module.LegacyOrder.objects.select_related("custno").get(pk=order.pk)
        # CHAR is fixed-length: Db2 for i pads the value with blanks, and the
        # backend returns it as stored (Known Limitations); comparisons ignore
        # the padding.
        assert row.custno.name == "Acme".ljust(30)
        assert row.custno.credit == Decimal("1250.50")
        assert row.placed == placed
        assert module.LegacyCustomer.objects.filter(name="Acme", city="Gent").count() == 1
        module.LegacyCustomer.objects.filter(pk=customer.pk).update(credit=Decimal("99.99"))
        assert module.LegacyCustomer.objects.get(pk=customer.pk).credit == Decimal("99.99")
        module.LegacyOrder.objects.all().delete()
        module.LegacyCustomer.objects.all().delete()
